def _gpu_exports(plan: Plan) -> list[str]:
    aux = {plan.embedding.gpu.selector, plan.reranker.gpu.selector, plan.vl.gpu.selector}
    lines = [f"export MAIN_GPU={shlex.quote(plan.main.gpu.selector)}"]
    if len(aux) == 1:
        lines.append(f"export AUX_GPU={shlex.quote(next(iter(aux)))}")
    else:
        lines.append(f"export EMBED_GPU={shlex.quote(plan.embedding.gpu.selector)}")
        lines.append(f"export RERANK_GPU={shlex.quote(plan.reranker.gpu.selector)}")
        lines.append(f"export VL_GPU={shlex.quote(plan.vl.gpu.selector)}")
    return lines


def build_start_sh(plan: Plan) -> str:
    gpu_lines = "\n".join(f"#   {gpu.describe()}" for gpu in plan.gpus)
    offload = (
        "-ngl auto --fit on(自動 VRAM 配置)"
        if plan.parameters.get("fit") == "on"
        else "-ngl 99(全 GPU offload)"
    )
    exports = "\n".join(_gpu_exports(plan))
    return f"""#!/usr/bin/env bash
# {GENERATED_MARKER} — {time.strftime("%Y-%m-%d %H:%M:%S")}
# 重新設定:cd {REPO_ROOT} && ./set_config.sh
#
# 偵測到的 GPU:
{gpu_lines}
#
# 配置(模型 @ GPU index):
#   main      = {plan.main_key} @ GPU {plan.main.gpu.index}
#   embedding = {plan.embedding.candidate.path.name} @ GPU {plan.embedding.gpu.index}
#   reranker  = {plan.reranker.candidate.path.name} @ GPU {plan.reranker.gpu.index}
#   vl        = {plan.vl.candidate.path.name} @ GPU {plan.vl.gpu.index}
#
# 推薦啟動參數:ctx={plan.ctx}, threads={plan.parameters.get("threads")}, {offload}
#   完整參數在 ~/.config/codetrail/deployment.json;實際指令預覽:~/start.sh --dry-run
# 停止全部 server:{REPO_ROOT}/scripts/quit.sh
set -euo pipefail

export AICODE_MODEL={shlex.quote(plan.main_key)}
{exports}

exec {shlex.quote(str(REPO_ROOT / "scripts" / "start-all.sh"))} "$@"
"""


def write_start_sh(plan: Plan, start_path: Path, notes: list[str], dry_run: bool) -> None:
    content = build_start_sh(plan)
    if dry_run:
        print(f"\n--- [dry-run] 將寫入 {start_path} ---\n{content}", end="")
        return
    if start_path.exists() and GENERATED_MARKER not in start_path.read_text(
        encoding="utf-8", errors="replace"
    ):
        notes.append(f"{start_path} 已存在且不是 set_config 產生的;原檔已備份後才覆寫。")
    _backup(start_path, notes)
    tmp = start_path.with_name(f"{start_path.name}.tmp.{os.getpid()}")
    tmp.write_text(content, encoding="utf-8")
    tmp.chmod(0o755)
    tmp.replace(start_path)


