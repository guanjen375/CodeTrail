def _shard_info(path: Path) -> tuple[Path, int, int] | None:
    """多 shard GGUF:回傳 (第 1 片路徑, 總大小, shard 數);非 shard 回 None。"""
    match = _SHARD_RE.match(path.name)
    if not match:
        return None
    stem, total = match.group("stem"), match.group("total")
    siblings = sorted(
        sib
        for sib in path.parent.glob("*.gguf")
        if (m := _SHARD_RE.match(sib.name)) and m.group("stem") == stem and m.group("total") == total
    )
    first = path.parent / f"{stem}-00001-of-{total}.gguf"
    if not first.is_file():
        first = siblings[0]
    return first, sum(sib.stat().st_size for sib in siblings), len(siblings)


def _shard_issues(path: Path) -> list[str]:
    """檢查多 shard 模型是否齊全:缺片、零大小、殘留 incomplete/lock 檔。"""
    match = _SHARD_RE.match(path.name)
    issues: list[str] = []
    if not match:
        try:
            if path.stat().st_size == 0:
                issues.append(f"{path.name} 是零大小檔案(下載未完成?)")
        except OSError as exc:
            issues.append(f"{path.name} 無法讀取:{exc}")
        return issues

    stem, total_str = match.group("stem"), match.group("total")
    expected = int(total_str)
    present: dict[int, Path] = {}
    for sib in path.parent.glob("*.gguf"):
        m = _SHARD_RE.match(sib.name)
        if m and m.group("stem") == stem and m.group("total") == total_str:
            present[int(m.group("idx"))] = sib
    missing = [f"{stem}-{idx:05d}-of-{total_str}.gguf" for idx in range(1, expected + 1)
               if idx not in present]
    if missing:
        issues.append("缺少 shard:" + "、".join(missing))
    for idx, sib in sorted(present.items()):
        try:
            if sib.stat().st_size == 0:
                issues.append(f"{sib.name} 是零大小檔案(下載未完成?)")
        except OSError as exc:
            issues.append(f"{sib.name} 無法讀取:{exc}")
    leftovers = sorted(
        leftover.name
        for pattern in (f"{stem}*.incomplete", f"{stem}*.lock", f"{stem}*.part")
        for leftover in path.parent.glob(pattern)
    )
    if leftovers:
        issues.append("殘留未完成下載檔:" + "、".join(leftovers))
    return issues


def _candidate_files(candidate: ModelCandidate) -> list[Path]:
    """回傳單檔或依編號排序的完整 shard 路徑。"""
    match = _SHARD_RE.match(candidate.path.name)
    if not match:
        return [candidate.path]
    stem = match.group("stem")
    total_text = match.group("total")
    return [
        candidate.path.parent / f"{stem}-{index:05d}-of-{total_text}.gguf"
        for index in range(1, int(total_text) + 1)
    ]


def _gguf_exact(handle, size: int, path: Path) -> bytes:
    data = handle.read(size)
    if len(data) != size:
        raise SetupError(f"GGUF metadata 截斷:{path.name}")
    return data


def _gguf_u32(handle, path: Path) -> int:
    return struct.unpack("<I", _gguf_exact(handle, 4, path))[0]


def _gguf_u64(handle, path: Path) -> int:
    return struct.unpack("<Q", _gguf_exact(handle, 8, path))[0]


def _gguf_string(handle, path: Path, *, capture: bool) -> str | None:
    length = _gguf_u64(handle, path)
    if length > GIB:
        raise SetupError(f"GGUF string 長度異常:{path.name} ({length} bytes)")
    if capture:
        raw = _gguf_exact(handle, length, path)
        try:
            return raw.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise SetupError(f"GGUF string 不是 UTF-8:{path.name}") from exc
    handle.seek(length, os.SEEK_CUR)
    return None


def _consume_gguf_value(handle, value_type: int, path: Path, *, capture: bool = False,
                        depth: int = 0) -> object | None:
    """讀/略過一個 GGUF metadata value；只在 capture 時回傳 scalar/string。"""
    if depth > 2:
        raise SetupError(f"GGUF metadata array 巢狀過深:{path.name}")
    fixed = _GGUF_FIXED_TYPES.get(value_type)
    if fixed:
        fmt, size = fixed
        raw = _gguf_exact(handle, size, path)
        return struct.unpack(fmt, raw)[0] if capture else None
    if value_type == 8:  # STRING
        return _gguf_string(handle, path, capture=capture)
    if value_type == 9:  # ARRAY
        element_type = _gguf_u32(handle, path)
        count = _gguf_u64(handle, path)
        if count > 100_000_000:
            raise SetupError(f"GGUF metadata array 長度異常:{path.name} ({count})")
        element_fixed = _GGUF_FIXED_TYPES.get(element_type)
        if element_fixed:
            handle.seek(element_fixed[1] * count, os.SEEK_CUR)
        else:
            for _ in range(count):
                _consume_gguf_value(handle, element_type, path, depth=depth + 1)
        return None
    raise SetupError(f"GGUF metadata type 不支援:{path.name} (type={value_type})")


def _inspect_gguf_file(path: Path) -> ModelLayout:
    """只走 GGUF header/tensor table，以 offset 差計算 expert storage bytes。"""
    try:
        file_size = path.stat().st_size
        with path.open("rb") as handle:
            if _gguf_exact(handle, 4, path) != b"GGUF":
                raise SetupError(f"不是有效 GGUF(magic 不符):{path.name}")
            version = _gguf_u32(handle, path)
            if version not in {2, 3}:
                raise SetupError(f"GGUF version 不支援:{path.name} (v{version})")
            tensor_count = _gguf_u64(handle, path)
            metadata_count = _gguf_u64(handle, path)
            # split GGUF 允許某一片只帶 metadata、tensor_count=0。
            if tensor_count > 10_000_000:
                raise SetupError(f"GGUF tensor 數量異常:{path.name} ({tensor_count})")
            if metadata_count > 10_000_000:
                raise SetupError(f"GGUF metadata 數量異常:{path.name} ({metadata_count})")

            alignment = 32
            for _ in range(metadata_count):
                key = _gguf_string(handle, path, capture=True)
                value_type = _gguf_u32(handle, path)
                value = _consume_gguf_value(
                    handle, value_type, path, capture=key == "general.alignment"
                )
                if key == "general.alignment" and isinstance(value, int):
                    alignment = value
            if alignment < 1 or alignment > MIB or alignment & (alignment - 1):
                raise SetupError(f"GGUF alignment 異常:{path.name} ({alignment})")

            tensors: list[tuple[int, str]] = []
            for _ in range(tensor_count):
                name = _gguf_string(handle, path, capture=True)
                n_dims = _gguf_u32(handle, path)
                if n_dims > 16:
                    raise SetupError(f"GGUF tensor 維度異常:{path.name} ({n_dims})")
                _gguf_exact(handle, n_dims * 8, path)  # dimensions
                _gguf_u32(handle, path)                # ggml tensor type
                offset = _gguf_u64(handle, path)
                tensors.append((offset, name or ""))

            data_start = (handle.tell() + alignment - 1) // alignment * alignment
    except OSError as exc:
        raise SetupError(f"無法讀取 GGUF metadata:{path} ({exc})") from exc

    if not tensors:
        return ModelLayout(tensor_bytes=0, expert_bytes=0)
    tensors.sort()
    data_bytes = file_size - data_start
    if data_bytes <= 0:
        raise SetupError(f"GGUF 沒有 tensor data:{path.name}")
    total = 0
    expert = 0
    per_layer: dict[int, int] = {}
    for index, (offset, name) in enumerate(tensors):
        end = tensors[index + 1][0] if index + 1 < len(tensors) else data_bytes
        if offset < 0 or end <= offset or end > data_bytes:
            raise SetupError(f"GGUF tensor offset 異常:{path.name} ({name})")
        storage = end - offset
        total += storage
        if _CPU_MOE_TENSOR_RE.search(name):
            expert += storage
            blk = _BLK_INDEX_RE.search(name)
            if blk:
                layer = int(blk.group(1))
                per_layer[layer] = per_layer.get(layer, 0) + storage
    return ModelLayout(
        tensor_bytes=total,
        expert_bytes=expert,
        expert_layer_bytes=tuple(sorted(per_layer.items())),
    )


def inspect_model_layout(candidate: ModelCandidate) -> ModelLayout:
    """聚合所有 GGUF shards 的 tensor/expert bytes。"""
    total = 0
    expert = 0
    per_layer: dict[int, int] = {}
    for path in _candidate_files(candidate):
        layout = _inspect_gguf_file(path)
        total += layout.tensor_bytes
        expert += layout.expert_bytes
        for layer, size in layout.expert_layer_bytes:
            per_layer[layer] = per_layer.get(layer, 0) + size
    if total <= 0:
        raise SetupError(f"GGUF 沒有可分析的 tensor table:{candidate.path.name}")
    if expert > candidate.total_bytes:
        raise SetupError(f"GGUF expert tensor 容量異常:{candidate.path.name}")
    return ModelLayout(
        tensor_bytes=total,
        expert_bytes=expert,
        expert_layer_bytes=tuple(sorted(per_layer.items())),
    )


def scan_models(
    models_dir: Path, *, notes: list[str] | None = None
) -> tuple[dict[str, list[ModelCandidate]], list[str]]:
    if not models_dir.is_dir():
        raise SetupError(
            f"偵測失敗:找不到模型目錄 {models_dir}。"
            "請先依 README §2 下載 GGUF,或用 --models-dir 指定位置。"
        )
    try:
        ggufs = sorted(p for p in models_dir.rglob("*.gguf") if p.is_file())
    except PermissionError as exc:
        raise SetupError(f"偵測失敗:模型目錄無法讀取(權限不足):{exc}") from exc
    if not ggufs:
        raise SetupError(f"偵測失敗:{models_dir} 內沒有任何 .gguf 模型檔(README §2)。")

    mmprojs = [p for p in ggufs if "mmproj" in p.name.lower()]
    seen: set[Path] = set()
    broken: list[str] = []
    candidates: dict[str, list[ModelCandidate]] = {
        "main": [], "embedding": [], "reranker": [], "vl": []
    }

    # 先聚合成候選(shard 去重、剔除不完整),分類延後:mmproj 歸屬需要知道
    # 「同目錄還有幾顆模型」,平鋪目錄(所有 GGUF 混放)時不能把每顆主模型都當 VL。
    raw_candidates: list[ModelCandidate] = []
    for path in ggufs:
        if "mmproj" in path.name.lower():
            continue
        shard = _shard_info(path)
        if shard:
            first, total_bytes, shards = shard
            if first in seen:
                continue
            seen.add(first)
            candidate = ModelCandidate(path=first, total_bytes=total_bytes, shards=shards)
        else:
            if path in seen:
                continue
            seen.add(path)
            candidate = ModelCandidate(path=path, total_bytes=path.stat().st_size, shards=1)

        issues = _shard_issues(candidate.path)
        if issues:
            broken.append(f"{candidate.path.parent.name}/{candidate.path.name}:" + ";".join(issues))
            continue
        raw_candidates.append(candidate)

    def _haystack(cand: ModelCandidate) -> str:
        return f"{cand.path.parent.name}/{cand.path.name}".lower()

    # 每個目錄有幾顆「main/VL 類」模型(embedding/reranker 檔名可辨識,不參與計數)。
    mainlike_per_dir: dict[Path, int] = {}
    for cand in raw_candidates:
        haystack = _haystack(cand)
        if "rerank" in haystack or any(token in haystack for token in _EMBED_TOKENS):
            continue
        mainlike_per_dir[cand.path.parent] = mainlike_per_dir.get(cand.path.parent, 0) + 1

    ambiguous_dirs: list[Path] = []
    for candidate in raw_candidates:
        haystack = _haystack(candidate)
        sibling_mmproj = sorted(
            (mp for mp in mmprojs if mp.parent == candidate.path.parent),
            # 偏好 f16 mmproj(README §2.4 的預設下載)。
            key=lambda mp: (0 if "f16" in mp.name.lower() else 1, mp.name),
        )
        if "rerank" in haystack:
            candidates["reranker"].append(candidate)
        elif any(token in haystack for token in _EMBED_TOKENS):
            candidates["embedding"].append(candidate)
        else:
            if sibling_mmproj:
                ambiguous = mainlike_per_dir.get(candidate.path.parent, 0) > 1
                candidates["vl"].append(
                    ModelCandidate(
                        path=candidate.path,
                        total_bytes=candidate.total_bytes,
                        shards=candidate.shards,
                        # 混放目錄不得自動配對:mmproj 可能屬於同目錄的另一顆模型,
                        # 自動吞下去會讓錯的模型配 mmproj 當 VL(圖片分析輸出錯亂)。
                        mmproj=None if ambiguous
                        else (sibling_mmproj[0] if len(sibling_mmproj) == 1 else None),
                        mmproj_choices=tuple(sibling_mmproj),
                        mmproj_ambiguous=ambiguous,
                    )
                )
                if not ambiguous:
                    # 一目錄一模型(README §2 慣例)→ mmproj 配對明確:
                    # 標記 vl_paired,排序永遠在非 VL 之後,不會被自動選成 main。
                    candidate = ModelCandidate(
                        path=candidate.path,
                        total_bytes=candidate.total_bytes,
                        shards=candidate.shards,
                        vl_paired=True,
                    )
                elif candidate.path.parent not in ambiguous_dirs:
                    ambiguous_dirs.append(candidate.path.parent)
            candidates["main"].append(candidate)

    if notes is not None:
        for directory in ambiguous_dirs:
            notes.append(
                f"⚠ {directory} 內有多顆模型與 mmproj 混放,無法確定 mmproj 屬於哪顆模型:"
                "這些模型不會被自動視為 VL 專用。建議每顆模型一個目錄、"
                "mmproj 與它的 VL 模型放同一目錄(README §2.4)。"
            )

    for role, entries in candidates.items():
        hints = _VERIFIED_HINTS[role]

        def sort_key(cand: ModelCandidate) -> tuple:
            path_text = str(cand.path).lower()
            # tuple 的先後就是維護者 preference；不能只做 bool 命中後再按大小，
            # 否則同時裝有 qwen3.5-9b / qwen3-vl 時會讓較小的舊模型蓋過首選。
            hint_rank = next(
                (rank for rank, hint in enumerate(hints) if hint in path_text),
                len(hints),
            )
            size = -cand.total_bytes if role == "main" else cand.total_bytes
            return (cand.vl_paired, hint_rank, size, str(cand.path))

        entries.sort(key=sort_key)
    return candidates, broken


def precheck(gpus: list[Gpu], candidates: dict[str, list[ModelCandidate]],
             broken: list[str],
             overrides: dict[str, str | None] | None = None) -> list[str]:
    """背景初步判定;不 OK 直接 SetupError 通知,可過但要注意的回傳 warning 清單。

    使用者用 --main-model / --embed-model / ... 直接給 .gguf 路徑時,該類別
    即使掃描不到也算滿足(模型分散存放在 models-dir 之外是合法情境)。
    """
    warnings: list[str] = []
    overrides = overrides or {}

    def satisfied(role: str) -> bool:
        if candidates[role]:
            return True
        value = overrides.get(role)
        # 數字是「候選編號」,沒有候選就沒意義;路徑才可救援缺類別。
        return value is not None and not value.isdecimal()

    missing = {
        "main": "主聊天模型",
        "embedding": "embedding 模型(如 bge-m3)",
        "reranker": "reranker 模型(如 bge-reranker-v2-m3)",
        "vl": "VL 模型 + mmproj(如 qwen3.5-9b)",
    }
    lacking = [label for role, label in missing.items() if not satisfied(role)]
    if lacking:
        detail = ""
        if broken:
            detail = "\n以下模型因不完整被剔除(修復後重跑):\n  - " + "\n  - ".join(broken)
        raise SetupError(
            "初步判定不通過:~/models 缺少必要模型類別 → " + "、".join(lacking)
            + "。下載方式見 README §2;四類模型都是硬性需求。" + detail
        )
    for report in broken:
        warnings.append(f"模型不完整已剔除:{report}(重新執行原本的 hf download 即可補齊)")
    if len(gpus) < 2:
        warnings.append(
            "只偵測到 1 顆 GPU:主模型與三顆附屬模型將共用同一顆卡(可以跑,"
            "但雙卡分工更穩;RTX 5090 單卡實測見 docs/verified-reference-5090.md)。"
        )
    return warnings


