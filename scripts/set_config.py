DEFAULT_MAIN_BASE_URL = "http://localhost:8080"


def _opencode_template(plan: Plan, python_bin: str,
                       main_base_url: str | None = None) -> dict:
    mcp_command = (
        'root="${AICODE_ROOT:-$(git rev-parse --show-toplevel 2>/dev/null || pwd -P)}"; '
        f'AICODE_ROOT="$root" exec {shlex.quote(python_bin)} '
        f'{shlex.quote(str(REPO_ROOT / "mcp_server.py"))}'
    )
    # OpenCode 連的必須是 deployment 實際的 main endpoint:使用者手改過 port/base_url
    # 時(merge_existing_deployment 會保留),baseURL 不能仍寫死 8080。
    base_url = (main_base_url or DEFAULT_MAIN_BASE_URL).rstrip("/")
    return {
        "$schema": "https://opencode.ai/config.json",
        "share": "disabled",
        "autoupdate": False,
        "enabled_providers": ["llamacpp"],
        "model": f"llamacpp/{plan.main_key}",
        "small_model": f"llamacpp/{plan.main_key}",
        "provider": {
            "llamacpp": {
                "npm": "@ai-sdk/openai-compatible",
                "name": "llama.cpp local",
                "options": {"baseURL": f"{base_url}/v1", "apiKey": "dummy"},
                "models": {
                    plan.main_key: {
                        "name": plan.main_key,
                        "limit": {"context": plan.ctx, "output": 8192},
                    }
                },
            }
        },
        "mcp": {
            "codetrail": {
                "type": "local",
                "command": ["bash", "-lc", mcp_command],
                "enabled": True,
                "timeout": _opencode_timeout_ms(),
            }
        },
        "permission": dict(_OPENCODE_PERMISSION_TEMPLATE),
    }


def build_opencode_config(
    plan: Plan, python_bin: str, existing_path: Path,
    main_base_url: str | None = None,
) -> tuple[dict, list[str]]:
    """只合併 CodeTrail 管的欄位;保留使用者既有 provider / mcp / 主題等設定。

    回傳 (config, 變更清單)。既有檔不存在或無法解析 → 用完整範本。
    main_base_url 是合併後 deployment 的 main endpoint(手改 port 時非預設),
    baseURL 跟著它走,deployment 與 OpenCode 才不會各連各的 port。
    """
    template = _opencode_template(plan, python_bin, main_base_url)
    changes: list[str] = []
    existing: dict | None = None
    if existing_path.is_file():
        try:
            loaded = json.loads(existing_path.read_text(encoding="utf-8"))
            if isinstance(loaded, dict):
                existing = loaded
            else:
                changes.append("既有 opencode.json 不是 JSON object → 以完整範本重建(原檔已備份)")
        except (OSError, json.JSONDecodeError):
            changes.append("既有 opencode.json 無法解析 → 以完整範本重建(原檔已備份)")
    if existing is None:
        if not changes:
            changes.append("建立新的 opencode.json(完整範本)")
        return template, changes

    merged = json.loads(json.dumps(existing))  # 深拷貝

    providers = merged.get("enabled_providers")
    if isinstance(providers, list):
        if "llamacpp" not in providers:
            providers.append("llamacpp")
            changes.append("enabled_providers 加入 'llamacpp'(保留你原本啟用的 provider)")
        extra = [p for p in providers if p != "llamacpp"]
        if extra:
            changes.append(
                f"⚠ enabled_providers 仍包含其他 provider({', '.join(map(str, extra))});"
                "NDA 場景建議只留 llamacpp"
            )
    else:
        merged["enabled_providers"] = ["llamacpp"]
        changes.append("設定 enabled_providers = ['llamacpp']")

    for key in ("model", "small_model"):
        new_value = template[key]
        if merged.get(key) != new_value:
            old = merged.get(key)
            merged[key] = new_value
            changes.append(f"{key}: {old!r} → {new_value!r}")

    # 合法 JSON 但型別不對(provider/mcp/models 不是 object)也不能 traceback:
    # 換成範本區塊並在變更清單說明(原檔已備份),其餘使用者設定照常保留。
    provider = merged.get("provider")
    if not isinstance(provider, dict):
        if provider is not None:
            changes.append("⚠ 既有 provider 不是 JSON object → 以範本重建該區塊(原值在備份)")
        provider = {}
        merged["provider"] = provider
    llamacpp = provider.get("llamacpp")
    if not isinstance(llamacpp, dict):
        provider["llamacpp"] = template["provider"]["llamacpp"]
        changes.append("新增 provider.llamacpp(其他 provider 設定保留)")
    else:
        llamacpp["npm"] = template["provider"]["llamacpp"]["npm"]
        llamacpp["name"] = template["provider"]["llamacpp"]["name"]
        old_options = llamacpp.get("options")
        llamacpp["options"] = template["provider"]["llamacpp"]["options"]
        if isinstance(old_options, dict) and \
                old_options.get("baseURL") != llamacpp["options"]["baseURL"]:
            changes.append(
                f"provider.llamacpp.options.baseURL: {old_options.get('baseURL')!r} → "
                f"{llamacpp['options']['baseURL']!r}(對齊 deployment 的 main endpoint)"
            )
        models = llamacpp.get("models")
        if not isinstance(models, dict):
            if models is not None:
                changes.append(
                    "⚠ 既有 provider.llamacpp.models 不是 JSON object → 重建(原值在備份)"
                )
            models = {}
            llamacpp["models"] = models
        models[plan.main_key] = template["provider"]["llamacpp"]["models"][plan.main_key]
        changes.append(
            f"provider.llamacpp.models 加入/更新 '{plan.main_key}'"
            f"(limit.context={plan.ctx};你其他的本機模型項目保留)"
        )

    mcp = merged.get("mcp")
    if not isinstance(mcp, dict):
        if mcp is not None:
            changes.append("⚠ 既有 mcp 不是 JSON object → 以範本重建該區塊(原值在備份)")
        mcp = {}
        merged["mcp"] = mcp
    mcp["codetrail"] = template["mcp"]["codetrail"]
    changes.append("mcp.codetrail 更新為偵測到的 Python 與 mcp_server.py 路徑(其他 MCP server 保留)")

    permission = merged.get("permission")
    if not isinstance(permission, dict):
        merged["permission"] = dict(_OPENCODE_PERMISSION_TEMPLATE)
        changes.append("加入 CodeTrail 建議的 deny-all permission 範本")
    else:
        added, conflicts = [], []
        for key, value in _OPENCODE_PERMISSION_TEMPLATE.items():
            if key not in permission:
                permission[key] = value
                added.append(key)
            elif permission[key] != value:
                conflicts.append(f"{key}(你設 {permission[key]!r},建議 {value!r})")
        if added:
            changes.append(f"permission 補上缺少的 {len(added)} 個鍵(依 CodeTrail 範本)")
        if conflicts:
            changes.append(
                "⚠ permission 與 CodeTrail 建議不同、已尊重你的設定:" + "、".join(conflicts)
                + " —— 放寬這些會讓 OpenCode 內建工具繞過 CodeTrail 沙箱(docs/security.md)"
            )

    for key in ("share", "autoupdate"):
        if key not in merged:
            merged[key] = template[key]
        elif merged[key] != template[key]:
            changes.append(f"⚠ {key}={merged[key]!r} 與建議值 {template[key]!r} 不同,已保留你的設定")
    merged.setdefault("$schema", template["$schema"])
    return merged, changes


def _gpu_exports(plan: Plan) -> list[str]:
    aux = {plan.embedding.gpu.selector, plan.reranker.gpu.selector, plan.vl.gpu.selector}
    lines = [f"export MAIN_GPU={shlex.quote(plan.main.gpu.selector)}"]
    if len(aux) == 1:
        lines.append(f"export AUX_GPU={shlex.quote(next(iter(aux)))}")
    else:
        lines.append(f"export EMBED_GPU={shlex.quote(plan.embedding.gpu.selector)}")
        lines.append(f"export RERANK_GPU={shlex.quote(plan.reranker.gpu.selector)}")
        lines.append(f"export VL_GPU={shlex.quote(plan.vl.gpu.selector)}")
    return lines


def _offload_description(plan: Plan) -> str:
    suffix = " --fit off" if plan.parameters.get("fit") == "off" else ""
    if plan.parameters.get("n_cpu_moe") is not None:
        return (
            f"CPU-MoE(部分): -ngl 99 --n-cpu-moe {plan.parameters['n_cpu_moe']}"
            f"{suffix}(只套 main)"
        )
    if plan.parameters.get("cpu_moe"):
        return f"CPU-MoE: -ngl 99 --cpu-moe{suffix}(只套 main)"
    return f"一般模式: -ngl 99{suffix}(全 GPU offload)"


