def _backup(path: Path, notes: list[str]) -> Path | None:
    if path.exists():
        stamp = time.strftime("%Y%m%d-%H%M%S")
        backup = path.with_name(f"{path.name}.bak-setconfig-{stamp}")
        shutil.copy2(path, backup)
        notes.append(f"已備份原有 {path} → {backup.name}")
        return backup
    return None


def _manifest_path(home: Path) -> Path:
    return home / ".config" / "codetrail" / "setconfig-last-transaction.json"


_SENSITIVE_KEY_RE = re.compile(r"(?i)api[_-]?key|token|secret|password|authorization|credential")
_REDACTED = "***redacted***"


def _redact_for_display(content: str) -> str:
    """dry-run 印出用:JSON 內容中憑證類欄位的值以遮罩取代。

    --dry-run 常被貼進 issue 或跑在 CI log;合併後的 opencode.json 會帶著使用者
    既有 provider 的 apiKey,原文印出等於把憑證寫進 log。只影響顯示,不影響寫入。
    """
    changed = False

    def _walk(node):
        nonlocal changed
        if isinstance(node, dict):
            result = {}
            for key, value in node.items():
                if isinstance(value, str) and value and \
                        isinstance(key, str) and _SENSITIVE_KEY_RE.search(key):
                    result[key] = _REDACTED
                    changed = True
                else:
                    result[key] = _walk(value)
            return result
        if isinstance(node, list):
            return [_walk(item) for item in node]
        return node

    try:
        data = json.loads(content)
    except ValueError:
        return content
    redacted = _walk(data)
    if not changed:
        return content
    return json.dumps(redacted, ensure_ascii=False, indent=2) + "\n"


def commit_files(targets: list[tuple[Path, str, int]], notes: list[str], dry_run: bool,
                 home: Path | None = None) -> None:
    """四個產物的 transaction:全部先寫 staging,備份既有檔,再逐一原子替換;
    任一步失敗 → 還原備份、清掉 staging,不留半套狀態。成功後寫入 transaction
    manifest(同一次設定的備份對應表),讓 --restore-last-backup 能整批一致還原。"""
    if dry_run:
        for path, content, _mode in targets:
            display = _redact_for_display(content)
            suffix = "(憑證類欄位值已遮罩;實際寫入不受影響)" if display != content else ""
            print(f"\n--- [dry-run] 將寫入 {path}{suffix} ---\n{display}", end="")
        return

    def _real_target(path: Path) -> Path:
        # dotfiles 使用者常把 ~/.config 下的檔案做成 symlink;os.replace 會把
        # 連結本身換成一般檔。改寫到連結目標,保留使用者的連結結構。
        if not path.is_symlink():
            return path
        try:
            real = path.resolve()
        except (OSError, RuntimeError):
            return path
        notes.append(f"{path} 是 symlink → 實際寫入 {real}(保留連結)。")
        return real

    staged: list[tuple[Path, Path, Path, int]] = []
    try:
        for path, content, mode in targets:
            real = _real_target(path)
            real.parent.mkdir(parents=True, exist_ok=True)
            tmp = real.with_name(f"{real.name}.setconfig-staging-{os.getpid()}")
            tmp.write_text(content, encoding="utf-8")
            tmp.chmod(mode)
            staged.append((tmp, path, real, mode))
    except BaseException:
        for tmp, _path, _real, _mode in staged:
            tmp.unlink(missing_ok=True)
        raise

    backups: dict[Path, Path | None] = {}
    existed: dict[Path, bool] = {}
    replaced: list[tuple[Path, Path]] = []
    try:
        for _tmp, path, real, _mode in staged:
            existed[path] = path.exists()
            backups[path] = _backup(real, notes)
        for tmp, path, real, _mode in staged:
            os.replace(tmp, real)
            replaced.append((path, real))
    except BaseException:
        for path, real in replaced:
            backup = backups.get(path)
            if backup is not None:
                shutil.copy2(backup, real)
            else:
                real.unlink(missing_ok=True)
        for tmp, _path, _real, _mode in staged:
            Path(tmp).unlink(missing_ok=True)
        raise

    global _COMMITTED
    _COMMITTED = True

    if home is not None:
        manifest = {
            "transaction": time.strftime("%Y%m%d-%H%M%S"),
            "targets": {
                str(path): {
                    "existed": existed.get(path, False),
                    "backup": str(backups[path]) if backups.get(path) else None,
                }
                for _tmp, path, _real, _mode in staged
            },
        }
        try:
            _manifest_path(home).write_text(
                json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
            )
        except OSError as exc:
            notes.append(f"⚠ transaction manifest 寫入失敗({exc});--restore-last-backup 會退回逐檔模式。")


def restore_last_backup(home: Path, dry_run: bool = False) -> int:
    """依最近一次 transaction manifest 整批還原:當時存在的檔案還原備份、
    當時不存在的檔案刪除。沒有 manifest 才退回「逐檔最新備份」的舊行為。
    dry_run=True 只列出會做的動作,不動任何檔案(--dry-run 的承諾對這條路也成立)。"""
    prefix = "[dry-run] 會" if dry_run else "已"
    manifest_file = _manifest_path(home)
    if manifest_file.is_file():
        try:
            manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
            targets = manifest.get("targets", {})
        except (OSError, json.JSONDecodeError) as exc:
            print(f"[set_config] manifest 無法解析({exc}),退回逐檔模式。", file=sys.stderr)
            targets = {}
        if targets:
            print(f"[set_config] 依 transaction {manifest.get('transaction')} 整批還原:")
            restored = 0
            for target_str, info in targets.items():
                target = Path(target_str)
                if info.get("existed") and info.get("backup"):
                    backup = Path(info["backup"])
                    if backup.is_file():
                        if not dry_run:
                            shutil.copy2(backup, target)
                        print(f"  {prefix}還原 {target} ← {backup.name}")
                        restored += 1
                    else:
                        print(f"  ⚠ 備份不見了:{backup}(略過 {target.name})")
                else:
                    if not dry_run:
                        target.unlink(missing_ok=True)
                    print(f"  {prefix}移除 {target}(該次設定前不存在)")
                    restored += 1
            if dry_run:
                print(f"[dry-run] 以上 {restored}/{len(targets)} 個動作未執行(拿掉 --dry-run 才會還原)。")
            else:
                print(f"[set_config] 完成:{restored}/{len(targets)} 個檔案回到該次設定前狀態。")
            return 0 if restored else 2

    # 舊備份(無 manifest)的退路:逐檔取最新備份,可能混合不同次設定。
    print("[set_config] 找不到 transaction manifest,退回逐檔最新備份(可能混合不同次設定):")
    targets = [
        home / ".config" / "codetrail" / "models.json",
        home / ".config" / "codetrail" / "deployment.json",
        home / ".config" / "opencode" / "opencode.json",
        home / "start.sh",
    ]
    restored = 0
    for target in targets:
        backups = sorted(target.parent.glob(f"{target.name}.bak-setconfig-*"))
        if not backups:
            print(f"  (略過)沒有 {target.name} 的備份")
            continue
        latest = backups[-1]
        if not dry_run:
            shutil.copy2(latest, target)
        print(f"  {prefix}還原 {target} ← {latest.name}")
        restored += 1
    if restored == 0:
        print("[set_config] 找不到任何 *.bak-setconfig-* 備份,未做任何變更。")
        return 2
    if dry_run:
        print(f"[dry-run] 以上 {restored} 個還原動作未執行(拿掉 --dry-run 才會還原)。")
    else:
        print(f"[set_config] 已還原 {restored} 個檔案。")
    return 0


