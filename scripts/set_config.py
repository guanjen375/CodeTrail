@dataclass(frozen=True)
class Gpu:
    index: int
    name: str
    total_mib: int
    free_mib: int
    uuid: str

    @property
    def selector(self) -> str:
        """啟動時綁 GPU 用的識別:UUID 比 index 穩(PCI 順序可能變)。"""
        return self.uuid if self.uuid and self.uuid != "N/A" else str(self.index)

    def describe(self) -> str:
        return f"GPU {self.index}: {self.name} | VRAM {self.total_mib} MiB(free {self.free_mib} MiB)"


@dataclass(frozen=True)
class ModelCandidate:
    path: Path            # 多 shard 模型固定指向第 1 片
    total_bytes: int      # 含所有 shard
    shards: int
    mmproj: Path | None = None            # 目錄內唯一 mmproj 時的自動配對
    mmproj_choices: tuple[Path, ...] = () # 目錄內有多個 mmproj 時的候選(需使用者選)
    vl_paired: bool = False               # 有 mmproj 配對的 VL 模型(不自動當 main)
    mmproj_ambiguous: bool = False        # 混放目錄:多顆模型共用 mmproj,歸屬需明確確認

    def describe(self) -> str:
        size = f"{self.total_bytes / GIB:.1f} GB"
        extra = f",{self.shards} shards" if self.shards > 1 else ""
        mm = f" + mmproj: {self.mmproj.name}" if self.mmproj else ""
        if not self.mmproj and self.mmproj_ambiguous:
            mm = "(混放目錄:mmproj 歸屬需明確確認)"
        elif not self.mmproj and self.mmproj_choices:
            mm = f"(同目錄有 {len(self.mmproj_choices)} 個 mmproj,需選擇)"
        vl = "(VL 模型)" if self.vl_paired and not mm else ""
        return f"{self.path.name}({size}{extra}){mm}{vl}"


@dataclass(frozen=True)
class ModelLayout:
    """從 GGUF tensor table 取得的 placement 資訊(不讀 tensor 內容)。"""

    tensor_bytes: int
    expert_bytes: int
    # (block 編號, 該層 expert storage bytes),block 編號由小到大;
    # 供 --n-cpu-moe 提問顯示層數範圍與「超過最大編號=全放 RAM」判斷,非 MoE 為空。
    expert_layer_bytes: tuple[tuple[int, int], ...] = ()
    # GGUF metadata 的 general.architecture 與 <arch>.expert_count。
    # 只用來讓「這顆是 dense」這句話可以被使用者驗證,以及在 metadata 說有 experts
    # 卻沒有任何 tensor 符合 llama.cpp offload 規則時發出警告 —— 判斷是否套用
    # CPU-MoE 的權威仍是 tensor 名稱(那才是 --cpu-moe 真正會抓的東西)。
    architecture: str = ""
    expert_count: int = 0

    @property
    def is_moe(self) -> bool:
        return self.expert_bytes > 0

    @property
    def metadata_claims_moe(self) -> bool:
        """metadata 宣稱是 MoE,但 tensor 名稱對不上 llama.cpp 的 offload 規則。"""
        return self.expert_count > 0 and not self.is_moe


