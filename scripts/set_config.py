def run(args: argparse.Namespace) -> int:
    home = Path(os.path.expanduser("~"))
    if args.restore_last_backup:
        return restore_last_backup(home, dry_run=args.dry_run)

    # 旗標的早期友善驗證(choose_int 也會擋;這裡在做任何偵測前先給清楚訊息)。
    if args.ctx is not None and not MIN_MAIN_CTX <= args.ctx <= MAX_MAIN_CTX:
        raise SetupError(
            f"--ctx 請設在 {MIN_MAIN_CTX}..{MAX_MAIN_CTX}"
            "(llama-server -c;過小會讓 RAG/工具流程無法運作)。"
        )
    if args.threads is not None and not 1 <= args.threads <= MAX_THREADS:
        raise SetupError(f"--threads 請設在 1..{MAX_THREADS}。")
    if args.reranker_ctx is not None and \
            not MIN_RERANKER_CTX <= args.reranker_ctx <= MAX_RERANKER_CTX:
        raise SetupError(f"--rerank-ctx 請設在 {MIN_RERANKER_CTX}..{MAX_RERANKER_CTX}。")

    # 相對路徑立刻轉絕對(不解 symlink):候選/registry 全存絕對路徑,
    # 否則 --models-dir ./models 會一路活到最後 schema 驗證才爆。
    models_dir = Path(os.path.abspath(
        Path(args.models_dir or os.environ.get("MODELS_DIR") or (home / "models")).expanduser()
    ))

    print("=== CodeTrail set_config ===")
    base_notes: list[str] = []
    python_bin = _detect_python(args.skip_deps_check, base_notes)
    print(f"[1/5] [PASS] Python(MCP server 用):{python_bin}")
    _check_tmux(args.skip_binary_check, base_notes)
    llama_caps = check_llama_binary(args.skip_binary_check, base_notes)
    print(f"[2/5] [PASS] tmux 與 llama-server({_llama_bin()};--fit "
          f"{'支援' if llama_caps.get('fit') else '不支援'})")

    gpus = detect_gpus()
    print(f"[3/5] [PASS] 偵測到 {len(gpus)} 顆 NVIDIA GPU:")
    for gpu in gpus:
        print(f"      {gpu.describe()}")

    candidates, broken = scan_models(models_dir, notes=base_notes)
    print(f"[4/5] [PASS] 掃描 {models_dir}:main={len(candidates['main'])}、"
          f"embedding={len(candidates['embedding'])}、reranker={len(candidates['reranker'])}、"
          f"vl={len(candidates['vl'])} 個候選")

    overrides = {"main": args.main_model, "embedding": args.embed_model,
                 "reranker": args.rerank_model, "vl": args.vl_model}

    warnings = precheck(gpus, candidates, broken, overrides)
    print("[5/5] [PASS] 初步判定 OK:GPU 與四類模型(main / embedding / reranker / vl+mmproj)齊全")
    for warning in warnings:
        print(f"      ⚠ {warning}")

    # deployment/registry 的 env override(文件允許的自訂路徑)只影響 aicode/doctor
    # 等 runtime 讀取;本工具固定寫預設路徑,產生的 ~/start.sh 也刻意 unset 這些變數
    # (防 .bashrc 殘留)。設了卻不提醒,使用者會拿到「aicode 與 start.sh 各讀一份」。
    split_env = [
        key for key in ("AICODE_DEPLOYMENT_CONFIG", "AICODE_PROFILE",
                        "AICODE_MODEL_REGISTRY", "AICODE_MODEL_REGISTRY_FILE")
        if (os.environ.get(key) or "").strip()
    ]
    if split_env:
        base_notes.append(
            "⚠ 偵測到環境變數 " + "、".join(split_env)
            + ":本工具只寫入預設路徑(~/.config/codetrail/*),而 ~/start.sh 啟動時會刻意"
            " unset 這些 override——aicode/doctor 會讀你的自訂檔,~/start.sh 卻讀預設檔,"
            "兩邊將各用一份設定。建議 unset 後重跑;要用自訂檔請自行維護其內容。"
        )

    codetrail_dir = home / ".config" / "codetrail"
    # OpenCode 與本 repo 的 config.py/aicode 都會先讀 OPENCODE_CONFIG;
    # set_config 若寫死預設路徑,設了這個變數的使用者會拿到 PASS 但完全沒生效的設定。
    opencode_env = (os.environ.get("OPENCODE_CONFIG") or "").strip()
    if opencode_env:
        opencode_path = Path(os.path.abspath(Path(opencode_env).expanduser()))
        base_notes.append(
            f"OPENCODE_CONFIG 已設定 → OpenCode 設定寫入 {opencode_path}(非預設路徑)。"
        )
    else:
        opencode_path = home / ".config" / "opencode" / "opencode.json"
    start_path = home / "start.sh"
    if start_path.exists():
        try:
            if GENERATED_MARKER not in start_path.read_text(encoding="utf-8", errors="replace"):
                base_notes.append(
                    f"⚠ {start_path} 已存在且不是 set_config 產生的;原檔會備份後才覆寫"
                    "(不想覆寫請離開,先把該檔改名)。"
                )
        except OSError:
            pass

    def _gather(notes: list[str]) -> dict:
        """一趟互動問答 + 產物組裝(使用者題無預設值,只驗證輸入範圍)。"""
        # 互動也必須明確列出 main 候選,不能靜默拿排序第一顆;否則多顆
        # 大模型並存時,使用者會在不知道模型名稱的情況下替錯誤的模型選模式。
        main_cand = choose_candidate("【主聊天模型】", candidates["main"], args.main_model,
                                     assume_yes=args.yes, flag_name="--main-model")
        main_gpu = choose_gpu("【主聊天模型】", gpus, args.main_gpu,
                              assume_yes=args.yes, flag_name="--main-gpu")

        # 先決定 main 的 CPU-MoE / 一般模式,再詢問任何附屬模型選項。
        # GGUF 只讀 header/tensor table,不讀權重內容,也不執行模型。
        try:
            main_layout: ModelLayout | None = inspect_model_layout(main_cand)
        except SetupError as exc:
            main_layout = None
            notes.append(f"⚠ 主模型 placement metadata 無法分析:{exc}")
        is_moe = main_layout is not None and main_layout.is_moe

        # --n-cpu-moe(部分 offload)蘊含 CPU-MoE 模式;與 --cpu-moe/--no-cpu-moe
        # 在 argparse 層互斥,這裡只需補上模式 override 並驗證輸入對這顆模型合理。
        mode_override = args.cpu_moe
        if args.n_cpu_moe is not None:
            if not is_moe:
                raise SetupError(
                    "--n-cpu-moe 只對 MoE 主模型有意義:未在 "
                    f"{main_cand.path.name} 偵測到 expert tensors(或 GGUF 無法解析)。"
                )
            mode_override = True
        if mode_override is True and main_layout is not None and not main_layout.is_moe:
            raise SetupError(
                f"--cpu-moe 只對 MoE 主模型有意義:{main_cand.path.name} "
                "未偵測到 expert tensors。"
            )
        cpu_moe = choose_cpu_moe_mode(
            mode_override,
            assume_yes=args.yes,
            candidate=main_cand,
            layout=main_layout,
            supported=llama_caps.get("cpu_moe", False),
            notes=notes,
        )
        if cpu_moe and not llama_caps.get("cpu_moe", False):
            raise SetupError(
                "CPU-MoE 模式需要 llama-server 的 --cpu-moe,但目前 build 不支援。\n"
                "  修復:更新並重新 build llama.cpp(README §1.5),或改用 --no-cpu-moe。"
            )

        # 部分 CPU-MoE(--n-cpu-moe)檔位:--cpu-moe 明確代表「全部放 RAM」,不再詢問;
        # 其餘情況(互動答 y / --n-cpu-moe 旗標)由使用者輸入,只驗證範圍。
        n_cpu_moe: int | None = None
        if cpu_moe and is_moe and args.cpu_moe is not True:
            if not llama_caps.get("n_cpu_moe", False):
                if args.n_cpu_moe is not None:
                    raise SetupError(
                        "--n-cpu-moe 需要 llama-server 支援,但目前 build 沒有這個旗標。\n"
                        "  修復:更新並重新 build llama.cpp(README §1.5),或改用 --cpu-moe。"
                    )
                notes.append(
                    "⚠ 這個 llama-server 不支援 --n-cpu-moe(部分 offload)→ "
                    "使用全 CPU-MoE(--cpu-moe);更新並重新 build llama.cpp 後可用。"
                )
            else:
                n_cpu_moe = choose_n_cpu_moe(
                    args.n_cpu_moe, assume_yes=args.yes, layout=main_layout
                )

        embed_cand = choose_candidate("【embedding 模型】", candidates["embedding"],
                                      args.embed_model, assume_yes=args.yes,
                                      flag_name="--embed-model")
        embed_gpu = choose_gpu("【embedding 模型】", gpus, args.embed_gpu,
                               assume_yes=args.yes, flag_name="--embed-gpu")
        rerank_cand = choose_candidate("【reranker 模型】", candidates["reranker"],
                                       args.rerank_model, assume_yes=args.yes,
                                       flag_name="--rerank-model")
        rerank_gpu = choose_gpu("【reranker 模型】", gpus, args.rerank_gpu,
                                assume_yes=args.yes, flag_name="--rerank-gpu")
        reranker_ctx = choose_reranker_ctx(rerank_cand, args.reranker_ctx, assume_yes=args.yes)
        vl_cand = choose_candidate("【VL 模型】", candidates["vl"], args.vl_model,
                                   assume_yes=args.yes, flag_name="--vl-model")
        vl_gpu = choose_gpu("【VL 模型】", gpus, args.vl_gpu,
                            assume_yes=args.yes, flag_name="--vl-gpu")

        # 混放目錄(mmproj 歸屬不明)必然產生多顆 VL 候選:上面的 choose_candidate
        # 已保證互動必答、--yes 必給 --vl-model,不會自動吞排序第一名;
        # 使用者選定後,同目錄唯一 mmproj 由 resolve_vl_mmproj 配對。
        vl_mmproj = resolve_vl_mmproj(vl_cand, args.vl_mmproj, interactive=not args.yes)

        # 綁定是安全 opt-in,不是互動題:未給 --allow-remote 一律只綁 127.0.0.1。
        allow_remote = bool(args.allow_remote)

        ctx = choose_int("主模型 n_ctx(-c)", args.ctx, assume_yes=args.yes,
                         minimum=MIN_MAIN_CTX, maximum=MAX_MAIN_CTX, flag_name="--ctx")
        threads = choose_int("主模型 CPU threads(-t)", args.threads, assume_yes=args.yes,
                             minimum=1, maximum=MAX_THREADS, flag_name="--threads")
        if ctx < 8192:
            notes.append(
                f"⚠ 主模型 ctx={ctx} 偏小:CodeTrail 的 RAG/工具流程需要較大 context,"
                "OpenCode 的 limit.context 也會同步為此值。"
            )
        cores = os.cpu_count() or 0
        if cores and threads > cores:
            notes.append(f"⚠ threads={threads} 超過偵測到的核心數({cores}),通常反而較慢。")

        # 只剩 VL 模型可當 main 時要明確確認(自動排序已保證:有非 VL 候選就不會選到 VL)。
        if main_cand.vl_paired and args.main_model is None and all(
            cand.vl_paired for cand in candidates["main"]
        ):
            if not args.yes:
                while True:
                    raw = _input(
                        f"沒有非 VL 的主聊天模型;要把 VL 模型 {main_cand.path.name} 同時當 main 嗎?"
                        "(工具呼叫行為視模型而定;y/n): "
                    ).strip().lower()
                    if raw in {"y", "yes"}:
                        break
                    if raw in {"n", "no"}:
                        raise SetupError(
                            "已取消:請先下載一顆主聊天模型(README §2.2)再重跑 ./set_config.sh。"
                        )
                    print("  請輸入 y 或 n。")
            notes.append(
                f"⚠ 沒有非 VL 的主聊天模型候選,已把 VL 模型 {main_cand.path.name} 同時當 main"
                "(VL service 會再載一份)。工具呼叫品質視該模型而定;"
                "建議另外下載一顆主聊天模型(README §2.2)。"
                "若這其實是一般聊天模型,把同目錄的 mmproj 移到 VL 模型自己的目錄後重跑即可。"
            )

        plan = Plan(
            gpus=gpus,
            main=Selection("main", main_cand, main_gpu),
            embedding=Selection("embedding", embed_cand, embed_gpu),
            reranker=Selection("reranker", rerank_cand, rerank_gpu),
            vl=Selection("vl", vl_cand, vl_gpu, mmproj=vl_mmproj),
            main_key=sanitize_registry_key(main_cand.path),
            ctx=ctx,
            threads=threads,
            batch=0,
            ubatch=0,
            reranker_ctx=reranker_ctx,
            cpu_moe=cpu_moe,
            n_cpu_moe=n_cpu_moe,
            main_layout=main_layout,
            allow_remote=allow_remote,
            parameters={},
            notes=notes,
        )
        if args.reranker_ctx is not None:
            notes.append(reranker_ctx_effect(reranker_ctx))
        _warn_unverified_aux(plan)

        parameters, batch, ubatch = build_main_parameters(
            main_cand, ctx, threads, llama_caps.get("fit", True), cpu_moe, notes,
            n_cpu_moe=n_cpu_moe,
        )
        plan.parameters = parameters
        plan.batch = batch
        plan.ubatch = ubatch
        notes.append(
            f"附屬服務固定配置:三個服務 -np {AUX_PARALLEL};VL 最後啟動並用"
            f" -ngl auto --fit on --fit-target {VL_FIT_TARGET_MIB},依當下剩餘 VRAM"
            " 自動 offload(llama.cpp 會另計 mmproj worst-case memory)。"
        )
        notes.append(
            "本工具不做容量估算:VRAM/RAM 是否放得下,以 ~/start.sh 啟動後"
            " nvidia-smi 實測為準(啟動結尾會提醒)。"
        )
        if allow_remote:
            notes.append("⚠ --allow-remote:四個 llama-server 會綁 0.0.0.0,同網段任何人都能呼叫模型 API"
                         "(llama-server 無認證)。只在可信內網使用,必要時加防火牆規則。")

        registry = build_models_registry(plan, codetrail_dir / "models.json", notes)
        registry_json = json.dumps(registry, ensure_ascii=False, indent=2) + "\n"
        deployment_config = build_deployment_config(plan)
        merge_existing_deployment(deployment_config, codetrail_dir / "deployment.json", notes)
        deployment_json = json.dumps(deployment_config, ensure_ascii=False, indent=2) + "\n"
        # OpenCode 的 baseURL 必須對齊合併後 deployment 的 main endpoint
        # (使用者手改 port/base_url 時才會出現在 config;否則用預設 8080)。
        main_service = deployment_config["services"]["main"]
        main_base_url = main_service.get("base_url")
        if main_base_url is None and isinstance(main_service.get("port"), int):
            main_base_url = f"http://localhost:{main_service['port']}"
        opencode_config, opencode_changes = build_opencode_config(
            plan, python_bin, opencode_path, main_base_url
        )
        opencode_json = json.dumps(opencode_config, ensure_ascii=False, indent=2) + "\n"

        # 寫入正式檔之前,用 staging 內容跑一次 deployment_profile 完整驗證。
        validate_payloads(plan, deployment_json, registry_json)
        return {
            "plan": plan,
            "registry_json": registry_json,
            "deployment_json": deployment_json,
            "opencode_json": opencode_json,
            "opencode_changes": opencode_changes,
            "start_content": build_start_sh(plan),
        }

    notes = list(base_notes)
    bundle = _gather(notes)
    plan: Plan = bundle["plan"]
    _print_summary_page(plan, python_bin, bundle["opencode_changes"],
                        codetrail_dir, opencode_path, start_path)
    if not args.yes and not args.dry_run:
        while True:
            answer = _input("\n[Enter] 採用並寫入 / [q] 離開: ").strip().lower()
            if answer in {"", "y", "yes"}:
                break
            if answer == "q":
                print("[set_config] 已離開,未寫入任何檔案。")
                return 0
            print(f"  無效輸入 {answer!r}:Enter=採用寫入 / q=離開。")

    commit_mark = len(plan.notes)
    commit_files(
        [
            (codetrail_dir / "models.json", bundle["registry_json"], 0o644),
            (codetrail_dir / "deployment.json", bundle["deployment_json"], 0o644),
            # opencode.json 會保留使用者既有 provider 的 apiKey → 只給擁有者讀寫,
            # 也不能把使用者原本的 0600 重跑成 0644。
            (opencode_path, bundle["opencode_json"], 0o600),
            (start_path, bundle["start_content"], 0o755),
        ],
        plan.notes,
        args.dry_run,
        home=home,
    )
    for note in plan.notes[commit_mark:]:
        print(f"  - {note}")

    print("\n=== 結果 ===")
    if args.dry_run:
        print("[dry-run] 未寫入任何檔案;以上為將寫入的完整內容。")
    else:
        print("[PASS] 第 1 層:設定檔已寫入並通過 schema 驗證(備份:*.bak-setconfig-*)")
        print("[待執行] 第 2 層:實際啟動與模型載入 → ~/start.sh(成功與否以此為準)")
        print("[待執行] 第 3 層:啟動後健檢 → ~/start.sh status(或 ./scripts/check-status.sh --strict)")
        print(f"          與 AICODE_MODEL={plan.main_key} python scripts/doctor.py")

    preview_rc = 0
    if not args.dry_run and not args.no_preview:
        preview_rc = preview_start_commands(plan)

    if not args.dry_run:
        running = running_codetrail_sessions()
        if running:
            print(f"\n⚠ 偵測到 CodeTrail server 正在執行(tmux:{', '.join(running)});"
                  "新設定要重啟才會生效。")
            if args.yes:
                print("  之後執行:~/start.sh stop && ~/start.sh")
            else:
                answer = _input_optional(
                    "  [R] 現在自動重啟 / [S] 稍後自行重啟(Enter=S): ", "s"
                ).strip().lower()
                if answer == "r":
                    rc = _restart_servers(start_path)
                    if rc != 0:
                        return rc

    print("\n下一步:")
    print("  ~/start.sh                        # 啟動四個 llama-server(tmux)")
    print("  ~/start.sh status                 # 確認四個 server 都 ready")
    print("  cd <你要分析的專案> && aicode      # 進 TUI;/status 應顯示 codetrail Connected")
    print("  ~/start.sh stop                   # 收工:關掉全部 tmux server 視窗")
    return 1 if preview_rc != 0 else 0


def main(argv: list[str] | None = None) -> int:
    # C/POSIX locale 的終端印中文會 UnicodeEncodeError;劣化成替代字元,不要當機。
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(errors="replace")
            except (OSError, ValueError):
                pass
    args = _parser().parse_args(argv)
    try:
        return run(args)
    except SetupError as exc:
        print(f"\n[set_config] {exc}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        if _COMMITTED:
            print("\n[set_config] 已中斷:設定檔「已完整寫入」,中斷的只是後續預覽/重啟步驟;"
                  "可直接執行 ~/start.sh。(備份:*.bak-setconfig-*)", file=sys.stderr)
        else:
            print("\n[set_config] 已取消,未寫入任何檔案。(寫入採 transaction:要嘛全套完成、"
                  "要嘛完全未動;若過去跑過,舊檔的 .bak-setconfig-* 備份仍在)", file=sys.stderr)
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
