def _candidate_from_path(path: Path) -> ModelCandidate:
    """使用者直接給路徑時也要正確聚合多 shard 的總大小,並驗證齊全性。"""
    issues = _shard_issues(path)
    if issues:
        raise SetupError(f"{path.name} 不完整:" + ";".join(issues))
    shard = _shard_info(path)
    if shard:
        first, total_bytes, shards = shard
        return ModelCandidate(path=first, total_bytes=total_bytes, shards=shards)
    return ModelCandidate(path=path, total_bytes=path.stat().st_size, shards=1)


def _input(prompt: str) -> str:
    try:
        return input(prompt)
    except EOFError as exc:
        raise SetupError(
            "無互動輸入環境。請加 --yes 並用旗標提供所有必要值"
            "(--main-model/--ctx/...),見 ./set_config.sh --help。"
        ) from exc


def _input_optional(prompt: str, default: str = "") -> str:
    """非必要的收尾提問:沒有互動輸入(EOF)時採預設值,不中斷流程。"""
    try:
        return input(prompt)
    except EOFError:
        return default


def choose_candidate(
    role_label: str,
    entries: list[ModelCandidate],
    override: str | None,
    assume_yes: bool,
    *,
    flag_name: str,
) -> ModelCandidate:
    """模型選擇:沒有預設值。唯一候選自動選用;多候選必須輸入編號或路徑。"""
    if override is not None:
        if override.isdecimal():
            if not entries:
                raise SetupError(
                    f"{role_label}:掃描不到任何候選,無法用編號 {override} 指定;"
                    "請改給 .gguf 絕對路徑。"
                )
            pick = int(override)
            if not 1 <= pick <= len(entries):
                raise SetupError(f"{role_label}:選項編號 {pick} 不在 1..{len(entries)}。")
            return entries[pick - 1]
        path = Path(override).expanduser()
        if not path.is_file() or path.suffix.lower() != ".gguf":
            raise SetupError(f"{role_label}:{override} 不是存在的 .gguf 檔。")
        return _candidate_from_path(path)
    if len(entries) == 1:
        print(f"{role_label} 只有一個候選,自動選用:{entries[0].describe()}")
        return entries[0]
    if assume_yes:
        raise SetupError(
            f"{role_label}:有 {len(entries)} 個候選;--yes 模式需要用 {flag_name} "
            f"指定編號(1..{len(entries)})或 .gguf 絕對路徑。"
        )

    print(f"\n{role_label} — 偵測到的候選:")
    for pos, cand in enumerate(entries, start=1):
        print(f"  [{pos}] {cand.describe()}")
    while True:
        raw = _input(f"請輸入編號 1..{len(entries)}(或直接貼 .gguf 絕對路徑): ").strip()
        if raw.isdecimal():
            if 1 <= int(raw) <= len(entries):
                return entries[int(raw) - 1]
            print(f"  無效輸入:{raw}(編號只有 1..{len(entries)})")
            continue
        path = Path(raw).expanduser()
        if raw and path.is_file() and path.suffix.lower() == ".gguf":
            return _candidate_from_path(path)
        print(f"  無效輸入:{raw!r}(要嘛編號 1..{len(entries)},要嘛存在的 .gguf 路徑)")


def choose_gpu(
    role_label: str,
    gpus: list[Gpu],
    override: str | None,
    assume_yes: bool,
    *,
    flag_name: str,
) -> Gpu:
    """GPU 選擇:沒有預設值。單卡自動選用;多卡必須輸入偵測到的 index。"""
    by_index = {gpu.index: gpu for gpu in gpus}
    if override is not None:
        if not override.isdecimal() or int(override) not in by_index:
            raise SetupError(
                f"{role_label}:GPU index '{override}' 不在偵測結果中"
                f"(可用:{sorted(by_index)})。"
            )
        return by_index[int(override)]
    if len(gpus) == 1:
        return gpus[0]
    if assume_yes:
        raise SetupError(
            f"{role_label}:偵測到多顆 GPU;--yes 模式需要用 {flag_name} 指定 GPU index"
            f"(可用:{sorted(by_index)})。"
        )

    print(f"\n{role_label} — 要放哪顆 GPU?")
    for gpu in gpus:
        print(f"  [{gpu.index}] {gpu.describe()}")
    while True:
        raw = _input(f"請輸入 GPU index(可用:{sorted(by_index)}): ").strip()
        if raw.isdecimal() and int(raw) in by_index:
            return by_index[int(raw)]
        print(f"  無效的 GPU index:{raw!r}(可用:{sorted(by_index)})")


def choose_int(label: str, override: int | None, assume_yes: bool, *,
               minimum: int, maximum: int, flag_name: str) -> int:
    """數值輸入:沒有預設值,只驗證範圍(選項外的輸入會重問)。
    互動與旗標共用同一組上下限:互動不得寫入 CLI/schema 明令拒絕的值。"""
    if override is not None:
        if not minimum <= override <= maximum:
            raise SetupError(f"{label} 必須在 {minimum}..{maximum}。")
        return override
    if assume_yes:
        raise SetupError(
            f"--yes 模式需要用 {flag_name} 指定 {label}({minimum}..{maximum})。"
        )
    while True:
        raw = _input(f"{label}({minimum}..{maximum}): ").strip()
        if raw.isdecimal() and minimum <= int(raw) <= maximum:
            return int(raw)
        print(f"  無效輸入:請輸入 {minimum}..{maximum} 的整數。")


def reranker_ctx_effect(ctx: int) -> str:
    return (
        f"reranker ctx={ctx} 會同步設為 -c/-b/-ub;每筆 query+passage 未超過此上限時,"
        "單純加大 ctx 不會提高排序精準度;超過時可能失敗或必須截斷,才可能漏掉關鍵證據。"
        "ctx 越大越吃顯存,真的送入更多 token 時也會更慢。"
    )


def choose_reranker_ctx(
    candidate: ModelCandidate,
    override: int | None,
    assume_yes: bool,
) -> int:
    """Return the reranker service's internal buffer size.

    This is not the main-model n_ctx and should not be another normal setup
    question.  Keep the CLI override for unusual long-passage/OOM tuning, but
    otherwise use the deployment default silently.
    """
    del candidate, assume_yes
    if override is None:
        return DEFAULT_RERANKER_CTX
    return choose_int(
        "reranker internal buffer(-c/-b/-ub)", override, True,
        minimum=MIN_RERANKER_CTX, maximum=MAX_RERANKER_CTX, flag_name="--rerank-ctx",
    )


def choose_cpu_moe_mode(
    override: bool | None,
    assume_yes: bool,
    candidate: ModelCandidate,
    layout: ModelLayout | None,
    supported: bool,
    notes: list[str],
) -> bool:
    """主模型唯一一次的模式分流;附屬三模型永遠不套 CPU-MoE。

    不做容量估算、沒有預設答案:只依 GGUF 是否有 expert tensors 決定要不要問,
    要不要開由使用者自己決定(VRAM 放不放得下以啟動後 nvidia-smi 實測為準)。
    """
    if override is not None:
        return override
    if layout is None:
        notes.append(
            "⚠ 無法讀取主模型 GGUF tensor 配置 → 使用一般模式"
            "(確定是 MoE 要強制啟用時用 --cpu-moe)。"
        )
        return False
    if not layout.is_moe:
        return False  # dense 模型:CPU-MoE 無意義,不詢問。
    if not supported:
        notes.append(
            "⚠ 主模型是 MoE,但這個 llama-server build 不支援 --cpu-moe → 一般模式。"
            "更新並重新 build llama.cpp(README §1.5)後重跑可啟用。"
        )
        return False
    if assume_yes:
        raise SetupError(
            "主模型是 MoE:--yes 模式需要用 --cpu-moe / --no-cpu-moe / --n-cpu-moe "
            "明確指定運行模式。"
        )

    print("\n【主聊天模型運行模式】CPU-MoE 只套用 main,不影響 embedding/reranker/VL。")
    print(f"  目前主模型: {candidate.describe()}")
    print(f"  已偵測到 MoE expert tensors 約 {layout.expert_bytes / GIB:.1f} GiB。")
    print("  y = experts 放 RAM、dense/KV 留 GPU(--cpu-moe / --n-cpu-moe);"
          "n = 一般模式(全 GPU offload)。")
    while True:
        raw = _input("主聊天模型啟用 CPU-MoE? [y/n]: ").strip().lower()
        if raw in {"y", "yes"}:
            return True
        if raw in {"n", "no"}:
            return False
        print("  請輸入 y 或 n。")


def choose_n_cpu_moe(
    override: int | None,
    assume_yes: bool,
    layout: ModelLayout,
) -> int | None:
    """CPU-MoE 模式的部分 offload 檔位:純使用者輸入,只驗證範圍,不做容量估算。

    回傳 None = 全部 experts 留 RAM(--cpu-moe)。輸入超過最大 block 編號的值
    視同全部留 RAM(語意上等同 --cpu-moe,寫成布林鍵比較清楚)。
    """
    layers = layout.expert_layer_bytes
    max_index = layers[-1][0] if layers else 0
    if override is not None:
        return None if override > max_index else override
    if assume_yes:
        # _gather 保證 --yes 一定帶模式旗標:--cpu-moe 不會走到這裡,
        # --n-cpu-moe 則 override 非 None。防衛性維持全 CPU-MoE。
        return None

    print("\n【主模型 n-cpu-moe(部分 CPU-MoE)】")
    print("  --n-cpu-moe N = 前 N 層(blk 編號 < N)的 MoE experts 留 RAM,其餘塞回 GPU。")
    if layers:
        print(f"  這顆模型共 {len(layers)} 層 experts(blk.{layers[0][0]}..blk.{max_index});"
              f"輸入 ≥ {max_index + 1} = 全部 experts 留 RAM(等同 --cpu-moe)。")
    else:
        print("  這顆模型的 expert tensors 沒有 blk 編號;輸入 ≥ 1 = 全部 experts 留 RAM。")
    print("  N 越小 → 越多 experts 進 GPU、越吃顯存;塞不塞得下以啟動後 nvidia-smi 實測為準。")
    value = choose_int(
        "主模型 n-cpu-moe(--n-cpu-moe)", None, False,
        minimum=0, maximum=MAX_N_CPU_MOE, flag_name="--n-cpu-moe",
    )
    return None if value > max_index else value


def resolve_vl_mmproj(
    vl_cand: ModelCandidate,
    override: str | None,
    interactive: bool,
) -> Path:
    """mmproj 配對:唯一 → 自動;多個 → 必須選(不猜);沒有 → 停下並指路。"""
    if override:
        path = Path(override).expanduser()
        if not path.is_file() or path.suffix.lower() != ".gguf":
            raise SetupError(f"VL mmproj:{override} 不是存在的 .gguf 檔。")
        return path
    choices = list(vl_cand.mmproj_choices)
    if not choices:
        sibling = sorted(vl_cand.path.parent.glob("*mmproj*.gguf"))
        choices = sibling
    if not choices:
        raise SetupError(
            f"VL 模型 {vl_cand.path.name} 同目錄找不到 mmproj *.gguf;"
            "VL 模型與它的 mmproj 必須放在同一目錄(README §2.4),"
            "或用 --vl-mmproj 明確指定。"
        )
    if len(choices) == 1:
        return choices[0]
    if not interactive:
        listing = "、".join(p.name for p in choices)
        raise SetupError(
            f"VL 模型 {vl_cand.path.name} 同目錄有多個 mmproj({listing}),"
            "無法自動判斷相容配對(配錯會讓圖片分析輸出錯亂):"
            "請用 --vl-mmproj <絕對路徑> 明確指定,或互動重跑 ./set_config.sh 選擇。"
        )
    print(f"\n【VL mmproj】{vl_cand.path.name} 同目錄有多個 mmproj,請選擇相容的那個:")
    for pos, choice in enumerate(choices, start=1):
        print(f"  [{pos}] {choice.name}")
    while True:
        raw = _input(f"請輸入編號 1..{len(choices)}: ").strip()
        if raw.isdecimal() and 1 <= int(raw) <= len(choices):
            return choices[int(raw) - 1]
        print("  無效輸入。")


