def build_main_parameters(candidate: ModelCandidate, ctx: int, threads: int,
                          fit_supported: bool, cpu_moe: bool, notes: list[str], *,
                          n_cpu_moe: int | None = None) -> tuple[dict, int, int]:
    """依使用者選定的模式組裝主模型參數;不做容量估算,一律 -ngl 99。

    VRAM 放不放得下由使用者以啟動後 nvidia-smi 實測確認(~/start.sh 結尾會提醒)。
    """
    parameters: dict = {
        "jinja": True,
        "flash_attention": "on",
        "cache_type_k": "q8_0",
        "cache_type_v": "q8_0",
        "threads": threads,
    }
    if cpu_moe and n_cpu_moe is not None:
        # 使用者的部分 offload:--n-cpu-moe 與 --cpu-moe 互斥,同樣不與 --fit 混用。
        parameters.update({"gpu_layers": 99, "n_cpu_moe": n_cpu_moe})
        notes.append(
            f"主模型 {candidate.total_bytes / GIB:.0f} GB 採 CPU-MoE(部分)模式 → "
            f"前 {n_cpu_moe} 層 expert tensors 固定在 RAM(--n-cpu-moe {n_cpu_moe}),"
            "其餘 experts 與 dense 層全 GPU offload(-ngl 99);只影響 main。"
        )
    elif cpu_moe:
        parameters.update({"gpu_layers": 99, "cpu_moe": True})
        notes.append(
            f"主模型 {candidate.total_bytes / GIB:.0f} GB 採 CPU-MoE 模式 → "
            "全部 expert tensors 固定在 RAM(--cpu-moe),dense/其他層全 GPU offload(-ngl 99);"
            "只影響 main。"
        )
    else:
        parameters["gpu_layers"] = 99
        notes.append(
            f"主模型 {candidate.total_bytes / GIB:.0f} GB 採一般模式 → 全 GPU offload(-ngl 99);"
            "VRAM 用量請啟動後以 nvidia-smi 確認。"
        )
    if fit_supported:
        # 新版 llama.cpp 的 --fit 預設可能是 on;明確關閉才不會重寫使用者選定的
        # -ngl 99 / CPU-MoE placement。
        parameters["fit"] = "off"
    # schema 規定 ubatch ≤ batch ≤ ctx;小 ctx(CLI 允許到 1024)不夾限的話,
    # 使用者答完全部問題才會被自己的驗證打死。
    batch = min(2048, ctx)
    ubatch = min(512, batch)
    notes.append("取樣參數(temp/top-p/top-k)刻意不寫死:各模型官方建議不同,"
                 "需要時自行加進 ~/.config/codetrail/deployment.json 的 services.main.parameters。")
    return parameters, batch, ubatch


def sanitize_registry_key(path: Path) -> str:
    """檔名 → 合法 registry key(deployment_profile 的 _BARE_MODEL_RE:不含底線)。"""
    stem = _SHARD_RE.match(path.name)
    name = stem.group("stem") if stem else path.stem
    key = re.sub(r"[^A-Za-z0-9.+:-]+", "-", name).strip("-").lower()
    key = re.sub(r"-{2,}", "-", key)
    if not key or not key[0].isalnum():
        key = f"model-{key.lstrip('-.')}" if key else "main-model"
    return key[:64]


