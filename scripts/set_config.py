def _mem_total_bytes() -> int:
    try:
        with open("/proc/meminfo", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("MemTotal:"):
                    return int(line.split()[1]) * 1024
    except (OSError, ValueError, IndexError):
        pass
    return 0


def _llama_bin() -> Path:
    return Path(os.environ.get("LLAMA_BIN") or (Path.home() / "llama.cpp" / "build" / "bin" / "llama-server"))


def _llama_supports_fit(notes: list[str]) -> bool:
    """探測 llama-server 是否支援 `--fit`(新版自動 VRAM 配置)。"""
    binary = _llama_bin()
    if not binary.is_file():
        notes.append(
            f"找不到 llama-server({binary});先假設是支援 --fit 的新版。"
            "若尚未 build,見 README §1.5。"
        )
        return True
    try:
        proc = subprocess.run(
            [str(binary), "--help"], capture_output=True, text=True, timeout=30, check=False
        )
    except (OSError, subprocess.TimeoutExpired):
        return True
    return "--fit" in (proc.stdout + proc.stderr)


def recommend_main(plan_gpu: Gpu, candidate: ModelCandidate, ctx: int, threads: int,
                   fit_target: int, notes: list[str]) -> tuple[dict, int, int]:
    """依主模型大小 vs 所選 GPU VRAM 推薦 offload 策略與 batch。"""
    parameters: dict = {
        "jinja": True,
        "flash_attention": "on",
        "cache_type_k": "q8_0",
        "cache_type_v": "q8_0",
        "threads": threads,
    }
    fits_in_vram = candidate.total_bytes <= plan_gpu.total_mib * MIB * 0.85
    if fits_in_vram:
        parameters["gpu_layers"] = 99
        batch, ubatch = 2048, 512
        notes.append(
            f"主模型 {candidate.total_bytes / GIB:.0f} GB 可整顆放進 "
            f"{plan_gpu.name}({plan_gpu.total_mib} MiB)→ 全 GPU offload(-ngl 99)。"
        )
    else:
        batch, ubatch = 1024, 256
        if _llama_supports_fit(notes):
            parameters.update(
                {"gpu_layers": "auto", "fit": "on", "fit_target": fit_target, "parallel": 1}
            )
            notes.append(
                f"主模型 {candidate.total_bytes / GIB:.0f} GB 超過 {plan_gpu.name} 的 VRAM → "
                f"用 llama.cpp 自動配置(-ngl auto --fit on --fit-target {fit_target}),"
                "由 server 自行決定 GPU/CPU 層分配。"
            )
        else:
            parameters["gpu_layers"] = 99
            notes.append(
                "⚠ 你的 llama-server 不支援 --fit,且主模型大於 VRAM —— 這樣啟動很可能 OOM。"
                "建議更新並重新 build llama.cpp(README §1.5),"
                "或自行在 ~/.config/codetrail/deployment.json 調 n_cpu_moe。"
            )
    mem_total = _mem_total_bytes()
    if mem_total and mem_total > candidate.total_bytes + 32 * GIB:
        parameters["no_mmap"] = True
        notes.append("系統 RAM 足夠 → 加 --no-mmap(啟動載入較慢,但首次回應不再等 page-in)。")
    else:
        notes.append("系統 RAM 不寬裕 → 不加 --no-mmap(維持 mmap 懶載入,首次回應可能較慢)。")
    notes.append("取樣參數(temp/top-p/top-k)刻意不寫死:各模型官方建議不同,"
                 "需要時自行加進 ~/.config/codetrail/deployment.json 的 services.main.parameters。")
    return parameters, batch, ubatch


def sanitize_registry_key(path: Path) -> str:
    """檔名 → 合法 registry key(deployment_profile 的 _BARE_MODEL_RE:不含底線)。"""
    stem = _SHARD_RE.match(path.name)
    name = stem.group("stem") if stem else path.stem
    key = re.sub(r"[^A-Za-z0-9.+:-]+", "-", name).strip("-").lower()
    key = re.sub(r"-{2,}", "-", key)
    if not key or not key[0].isalnum():
        key = f"model-{key.lstrip('-.')}" if key else "main-model"
    return key[:64]


