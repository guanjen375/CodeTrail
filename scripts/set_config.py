def _candidate_from_path(path: Path) -> ModelCandidate:
    """使用者直接給路徑時也要正確聚合多 shard 的總大小,並驗證齊全性。"""
    issues = _shard_issues(path)
    if issues:
        raise SetupError(f"{path.name} 不完整:" + ";".join(issues))
    shard = _shard_info(path)
    if shard:
        first, total_bytes, shards = shard
        return ModelCandidate(path=first, total_bytes=total_bytes, shards=shards)
    return ModelCandidate(path=path, total_bytes=path.stat().st_size, shards=1)


def _input(prompt: str) -> str:
    try:
        return input(prompt)
    except EOFError as exc:
        raise SetupError(
            "無互動輸入環境。請改用旗標(--yes 全用預設,或 --main-model/--main-gpu/... "
            "個別指定),見 ./set_config.sh --help。"
        ) from exc


def _input_optional(prompt: str, default: str = "") -> str:
    """非必要的收尾提問:沒有互動輸入(EOF)時採預設值,不中斷流程。"""
    try:
        return input(prompt)
    except EOFError:
        return default


def _promote_candidate(entries: list[ModelCandidate], target: Path | None) -> bool:
    """把 path 等於 target 的候選移到清單最前(成為預設);回傳是否有促升。"""
    if target is None:
        return False
    for index, cand in enumerate(entries):
        try:
            same = cand.path.resolve() == target
        except OSError:
            same = False
        if same:
            if index:
                entries.insert(0, entries.pop(index))
            return True
    return False


def _existing_selection_paths(
    home: Path,
) -> tuple[dict[str, Path], list[str], dict[str, int | bool]]:
    """讀出目前設定檔指定的各角色模型路徑與主要數值(重跑時沿用,不靜默重設)。

    回傳 (role→仍存在的檔案路徑, 設定有指定但檔案已不存在的 role 清單,
    {"main_ctx"/"threads"/"reranker_ctx": 合理範圍內的既有值,
     "cpu_moe": 既有主模型模式})。
    main 透過 models.json registry 解析;vl_mmproj 是額外的虛擬 role。
    任何解析失敗都當作「沒有既有設定」,不阻擋流程。
    """
    config_path = home / ".config" / "codetrail" / "deployment.json"
    registry_path = home / ".config" / "codetrail" / "models.json"
    try:
        services = json.loads(config_path.read_text(encoding="utf-8")).get("services")
    except (OSError, ValueError):
        return {}, [], {}
    if not isinstance(services, dict):
        return {}, [], {}

    values: dict[str, int | bool] = {}
    main_service = services.get("main")
    if isinstance(main_service, dict):
        ctx = main_service.get("ctx")
        if isinstance(ctx, int) and not isinstance(ctx, bool) and \
                MIN_MAIN_CTX <= ctx <= 1_048_576:
            values["main_ctx"] = ctx
        params = main_service.get("parameters")
        threads = params.get("threads") if isinstance(params, dict) else None
        if isinstance(threads, int) and not isinstance(threads, bool) and 1 <= threads <= 1024:
            values["threads"] = threads
        if isinstance(params, dict):
            # 一般模式不寫 cpu_moe 鍵 → 鍵缺席即 False;有 parameters 就能斷定既有模式。
            values["cpu_moe"] = bool(params.get("cpu_moe"))
    rerank_service = services.get("reranker")
    if isinstance(rerank_service, dict):
        rerank_ctx = rerank_service.get("ctx")
        if isinstance(rerank_ctx, int) and not isinstance(rerank_ctx, bool) \
                and MIN_RERANKER_CTX <= rerank_ctx <= 1_048_576:
            values["reranker_ctx"] = rerank_ctx
    registry: dict = {}
    try:
        loaded = json.loads(registry_path.read_text(encoding="utf-8"))
        if isinstance(loaded, dict):
            registry = loaded
    except (OSError, ValueError):
        pass
    current: dict[str, Path] = {}
    missing: list[str] = []
    for role in ("main", "embedding", "reranker", "vl", "vl_mmproj"):
        service = services.get("vl" if role == "vl_mmproj" else role)
        if not isinstance(service, dict):
            continue
        value = service.get("mmproj" if role == "vl_mmproj" else "model")
        if role == "main" and isinstance(value, str):
            value = registry.get(value, value)
        if not isinstance(value, str) or not value.strip():
            continue
        try:
            path = Path(value).expanduser()
            if not path.is_absolute():
                continue
            resolved = path.resolve()
        except (OSError, RuntimeError):
            continue
        if resolved.is_file():
            current[role] = resolved
        else:
            missing.append(role)
    return current, missing, values


_START_GPU_EXPORT_RE = re.compile(r"^export (MAIN_GPU|AUX_GPU|EMBED_GPU|RERANK_GPU|VL_GPU)=(.+)$")


def _existing_gpu_selectors(start_path: Path) -> dict[str, str]:
    """從既有的(本工具產生的)~/start.sh 讀回各角色 GPU selector。

    GPU 分卡的唯一持久紀錄就是 start.sh 的 export(deployment.json 不存 gpu、
    runtime 只看環境變數),重跑要沿用使用者的分卡就得讀它。
    非本工具產生或任何解析失敗 → 空 dict(改用 VRAM 建議預設)。
    """
    try:
        text = start_path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {}
    if GENERATED_MARKER not in text:
        return {}
    raw: dict[str, str] = {}
    for line in text.splitlines():
        match = _START_GPU_EXPORT_RE.match(line.strip())
        if not match:
            continue
        try:
            parts = shlex.split(match.group(2))
        except ValueError:
            continue
        if len(parts) == 1 and parts[0]:
            raw[match.group(1)] = parts[0]
    selectors: dict[str, str] = {}
    if "MAIN_GPU" in raw:
        selectors["main"] = raw["MAIN_GPU"]
    for role, key in (("embedding", "EMBED_GPU"), ("reranker", "RERANK_GPU"), ("vl", "VL_GPU")):
        value = raw.get(key) or raw.get("AUX_GPU")
        if value:
            selectors[role] = value
    return selectors


def choose_candidate(
    role_label: str,
    entries: list[ModelCandidate],
    override: str | None,
    assume_yes: bool,
    default_marker: str = "(預設)",
) -> ModelCandidate:
    if override is not None:
        if override.isdecimal():
            if not entries:
                raise SetupError(
                    f"{role_label}:掃描不到任何候選,無法用編號 {override} 指定;"
                    "請改給 .gguf 絕對路徑。"
                )
            pick = int(override)
            if not 1 <= pick <= len(entries):
                raise SetupError(f"{role_label}:選項編號 {pick} 不在 1..{len(entries)}。")
            return entries[pick - 1]
        path = Path(override).expanduser()
        if not path.is_file() or path.suffix.lower() != ".gguf":
            raise SetupError(f"{role_label}:{override} 不是存在的 .gguf 檔。")
        return _candidate_from_path(path)
    if assume_yes:
        return entries[0]

    print(f"\n{role_label} — 偵測到的候選:")
    for pos, cand in enumerate(entries, start=1):
        marker = default_marker if pos == 1 else ""
        print(f"  [{pos}] {cand.describe()} {marker}")
    while True:
        raw = _input("請輸入編號(Enter 用預設,或直接貼 .gguf 絕對路徑): ").strip()
        if not raw:
            return entries[0]
        if raw.isdecimal() and 1 <= int(raw) <= len(entries):
            return entries[int(raw) - 1]
        path = Path(raw).expanduser()
        if path.is_file() and path.suffix.lower() == ".gguf":
            return _candidate_from_path(path)
        print(f"  無效輸入:{raw}(要嘛編號 1..{len(entries)},要嘛存在的 .gguf 路徑)")


def choose_gpu(
    role_label: str,
    gpus: list[Gpu],
    default: Gpu,
    override: str | None,
    assume_yes: bool,
) -> Gpu:
    by_index = {gpu.index: gpu for gpu in gpus}
    if override is not None:
        if not override.isdecimal() or int(override) not in by_index:
            raise SetupError(
                f"{role_label}:GPU index '{override}' 不在偵測結果中"
                f"(可用:{sorted(by_index)})。"
            )
        return by_index[int(override)]
    if assume_yes or len(gpus) == 1:
        return default

    print(f"{role_label} — 要放哪顆 GPU?")
    for gpu in gpus:
        marker = "(預設)" if gpu.index == default.index else ""
        print(f"  [{gpu.index}] {gpu.describe()} {marker}")
    while True:
        raw = _input(f"請輸入 GPU index(Enter 用預設 {default.index}): ").strip()
        if not raw:
            return default
        if raw.isdecimal() and int(raw) in by_index:
            return by_index[int(raw)]
        print(f"  無效的 GPU index:{raw}")


def choose_int(label: str, default: int, override: int | None, assume_yes: bool,
               *, minimum: int = 1) -> int:
    """互動與旗標共用同一個下限:互動不得寫入 CLI 明令拒絕的值(如 reranker ctx=1)。"""
    if override is not None:
        if override < minimum:
            raise SetupError(f"{label} 必須是 ≥ {minimum} 的整數。")
        return override
    if assume_yes:
        return default
    while True:
        raw = _input(f"{label}(Enter 用預設 {default}): ").strip()
        if not raw:
            return default
        if raw.isdecimal() and int(raw) >= minimum:
            return int(raw)
        print(f"  請輸入 ≥ {minimum} 的整數。")


def _candidate_is_qwen3_reranker(candidate: ModelCandidate) -> bool:
    haystack = str(candidate.path).lower()
    return any(hint in haystack for hint in _QWEN3_RERANKER_HINTS)


def recommended_reranker_ctx(candidate: ModelCandidate) -> int:
    """依已知 llama.cpp buffer 行為選可公開部署的保守預設。"""
    if _candidate_is_qwen3_reranker(candidate):
        return QWEN3_RERANKER_RECOMMENDED_CTX
    return DEFAULT_RERANKER_CTX


def reranker_ctx_effect(candidate: ModelCandidate, ctx: int) -> str:
    model_note = (
        "Qwen3 的 KV/compute buffer 對 ctx 特別敏感"
        if _candidate_is_qwen3_reranker(candidate)
        else "不同模型的顯存增幅不同"
    )
    return (
        f"reranker ctx={ctx} 會同步設為 -c/-b/-ub；每筆 query+passage 未超過此上限時，"
        "單純加大 ctx 不會提高排序精準度；超過時可能失敗或必須截斷，才可能漏掉關鍵證據。"
        f"ctx 越大可容納越長輸入，但會增加顯存；真的送入更多 token 時也會更慢（{model_note}）。"
    )


def choose_reranker_ctx(
    candidate: ModelCandidate,
    override: int | None,
    assume_yes: bool,
    *,
    default: int | None = None,
) -> int:
    if default is None:
        default = recommended_reranker_ctx(candidate)
    if override is not None or assume_yes:
        return choose_int("reranker context(-c/-b/-ub)", default, override,
                          assume_yes=True, minimum=MIN_RERANKER_CTX)

    print("\n【reranker ctx】")
    print(f"  目前模型: {candidate.path.name}")
    print("  ctx 是每筆 query+passage 可完整送入排序的 token 上限。")
    print("  輸入放得下時，ctx 設更大不會讓排序更準；太小導致失敗/截斷時才會漏證據。")
    print("  設大可處理更長 passage，但更吃顯存；實際送入更多 token 時也會更慢。")
    if _candidate_is_qwen3_reranker(candidate):
        print("  Qwen3 的 KV/compute buffer 對 ctx 特別敏感，因此建議先用 2048。")
    else:
        print("  BGE 的 8192 buffer 較省顯存，因此保留長 passage 的預設 8192。")
    return choose_int(
        "reranker context(-c/-b/-ub)", default, None, assume_yes=False,
        minimum=MIN_RERANKER_CTX,
    )


def choose_cpu_moe_mode(
    override: bool | None,
    assume_yes: bool,
    recommended: bool,
    candidate: ModelCandidate,
    layout: ModelLayout | None,
    *,
    capacity_recommended: bool | None = None,
    default_source: str = "capacity",
) -> bool:
    """主模型唯一一次的模式分流；附屬三模型永遠不套 CPU-MoE。

    recommended 是「預設值」;它可能來自容量估算(capacity)、既有設定(existing)
    或上一輪選擇(prior)。capacity_recommended 是純容量結論,分開傳才不會在
    沿用既有模式時印出「放不進 GPU」這類與事實不符的理由。
    """
    if capacity_recommended is None:
        capacity_recommended = recommended
    if override is not None:
        return override
    if assume_yes:
        return recommended

    print("\n【主聊天模型運行模式】CPU-MoE 只套用 main，不影響 embedding/reranker/VL。")
    print(f"  目前主模型: {candidate.describe()}")
    if layout is None:
        print(f"  ⚠ 無法讀取 {candidate.path.name} 的 GGUF tensor 配置，預設一般模式。")
    elif layout.is_moe:
        expert_gib = layout.expert_bytes / GIB
        print(f"  已偵測到 MoE expert tensors 約 {expert_gib:.1f} GiB。")
    else:
        print("  未偵測到 MoE expert tensors；dense 模型通常選一般模式。")
    if capacity_recommended:
        print("  主模型整顆放不進所選 GPU，建議 CPU-MoE（experts 放 RAM、dense/KV 留 GPU）。")
    if default_source == "existing":
        print("  預設沿用你目前設定的模式:" + ("CPU-MoE" if recommended else "一般模式")
              + "(重跑不悄悄改變模式)。")
    elif default_source == "prior":
        print("  預設沿用上一輪的選擇:" + ("CPU-MoE" if recommended else "一般模式") + "。")

    suffix = "Y/n" if recommended else "y/N"
    while True:
        raw = _input(f"主聊天模型啟用 CPU-MoE (--cpu-moe)? [{suffix}]: ").strip().lower()
        if not raw:
            return recommended
        if raw in {"y", "yes"}:
            return True
        if raw in {"n", "no"}:
            return False
        print("  請輸入 y 或 n。")


def resolve_vl_mmproj(
    vl_cand: ModelCandidate,
    override: str | None,
    interactive: bool,
) -> Path:
    """mmproj 配對:唯一 → 自動;多個 → 必須選(不猜);沒有 → 停下並指路。"""
    if override:
        path = Path(override).expanduser()
        if not path.is_file() or path.suffix.lower() != ".gguf":
            raise SetupError(f"VL mmproj:{override} 不是存在的 .gguf 檔。")
        return path
    choices = list(vl_cand.mmproj_choices)
    if not choices:
        sibling = sorted(vl_cand.path.parent.glob("*mmproj*.gguf"))
        choices = sibling
    if not choices:
        raise SetupError(
            f"VL 模型 {vl_cand.path.name} 同目錄找不到 mmproj *.gguf;"
            "VL 模型與它的 mmproj 必須放在同一目錄(README §2.4),"
            "或用 --vl-mmproj 明確指定。"
        )
    if len(choices) == 1:
        return choices[0]
    if not interactive:
        listing = "、".join(p.name for p in choices)
        raise SetupError(
            f"VL 模型 {vl_cand.path.name} 同目錄有多個 mmproj({listing}),"
            "無法自動判斷相容配對(配錯會讓圖片分析輸出錯亂):"
            "請用 --vl-mmproj <絕對路徑> 明確指定,或改跑 ./set_config.sh --advanced 互動選擇。"
        )
    print(f"\n【VL mmproj】{vl_cand.path.name} 同目錄有多個 mmproj,請選擇相容的那個:")
    for pos, choice in enumerate(choices, start=1):
        print(f"  [{pos}] {choice.name}")
    while True:
        raw = _input(f"請輸入編號 1..{len(choices)}: ").strip()
        if raw.isdecimal() and 1 <= int(raw) <= len(choices):
            return choices[int(raw) - 1]
        print("  無效輸入。")


