def _mem_info_mib() -> tuple[int, int]:
    """回傳 (MemTotal, MemAvailable) MiB；env path 僅供離線 fixture 注入。"""
    values: dict[str, int] = {}
    meminfo_path = os.environ.get("AICODE_SET_CONFIG_MEMINFO") or "/proc/meminfo"
    try:
        with open(meminfo_path, encoding="utf-8") as handle:
            for line in handle:
                key = line.partition(":")[0]
                if key in {"MemTotal", "MemAvailable", "MemFree"}:
                    values[key] = int(line.split()[1]) // 1024
    except (OSError, ValueError, IndexError):
        return 0, 0
    return values.get("MemTotal", 0), values.get("MemAvailable", values.get("MemFree", 0))


def _mem_total_bytes() -> int:
    return _mem_info_mib()[0] * MIB


def _is_qwen3_reranker(selection: Selection) -> bool:
    return selection.role == "reranker" and _candidate_is_qwen3_reranker(
        selection.candidate
    )


def _aux_overhead_mib(
    selection: Selection,
    reranker_ctx: int = DEFAULT_RERANKER_CTX,
) -> int:
    if _is_qwen3_reranker(selection):
        scaled = (
            QWEN3_RERANKER_REFERENCE_BUFFER_MIB * reranker_ctx
            + QWEN3_RERANKER_REFERENCE_CTX - 1
        ) // QWEN3_RERANKER_REFERENCE_CTX
        return max(AUX_OVERHEAD_MIB["reranker"], scaled)
    return AUX_OVERHEAD_MIB[selection.role]


def _aux_need_mib(
    selection: Selection,
    reranker_ctx: int = DEFAULT_RERANKER_CTX,
) -> int:
    """附屬服務的保守 VRAM 需求:GGUF(+mmproj)×1.1 + 各 role 的 buffer 概估。"""
    size = selection.candidate.total_bytes
    if selection.role == "vl" and selection.mmproj is not None:
        try:
            size += selection.mmproj.stat().st_size
        except OSError:
            pass
    return int(size * 1.1 / MIB) + _aux_overhead_mib(selection, reranker_ctx)


def _main_need_for_weights_mib(weight_bytes: int, ctx: int) -> int:
    overhead = MAIN_BASE_OVERHEAD_MIB + int(ctx / 32768 * MAIN_KV_PER_32K_MIB)
    return int(weight_bytes * 1.05 / MIB) + overhead


def _main_need_mib(candidate: ModelCandidate, ctx: int) -> int:
    return _main_need_for_weights_mib(candidate.total_bytes, ctx)


def _capacity_problem(message: str, ignore: bool, notes: list[str],
                      exc_type: type[SetupError] = SetupError) -> None:
    if ignore:
        notes.append("⚠(--ignore-capacity)" + message)
        return
    raise exc_type(message + "\n(明知風險仍要產生設定:--ignore-capacity)")


def _check_system_ram(
    resident_bytes: int,
    label: str,
    ignore: bool,
    notes: list[str],
) -> None:
    """CPU placement 的總 RAM hard gate；當下 available 另做啟動前提醒。"""
    total_mib, available_mib = _mem_info_mib()
    resident_mib = int(resident_bytes * 1.10 / MIB)
    if total_mib <= 0:
        _capacity_problem(
            f"容量判定不通過:讀不到系統 MemTotal，無法確認 {label} 是否會造成 RAM OOM。",
            ignore,
            notes,
        )
        return
    budget_mib = max(total_mib - SYSTEM_RAM_RESERVE_MIB, 0)
    notes.append(
        f"RAM 容量預估:總量 {total_mib} MiB − 保留 {SYSTEM_RAM_RESERVE_MIB} MiB"
        f" = 預算 {budget_mib} MiB；{label} 約需 {resident_mib} MiB。"
    )
    if resident_mib > budget_mib:
        _capacity_problem(
            f"容量判定不通過:{label} 約需 {resident_mib} MiB RAM，但系統預算只有"
            f" {budget_mib} MiB(總 RAM − 保留 {SYSTEM_RAM_RESERVE_MIB})。"
            "請換較小量化/模型，或增加 RAM。",
            ignore,
            notes,
        )
    if available_mib and available_mib < resident_mib:
        notes.append(
            f"⚠ 系統目前只有 {available_mib} MiB MemAvailable，但 {label} 規劃需"
            f" ~{resident_mib} MiB；啟動前先停掉舊 server/其他大型程序。"
        )


def plan_capacity(
    plan: Plan,
    fit_supported: bool,
    fit_target_arg: int,
    ignore: bool,
    notes: list[str],
) -> tuple[bool, int]:
    """整機容量可行性判定。

    1. 每張 GPU 預算 = 總 VRAM − 保留;先扣 aux(embedding/reranker/vl+mmproj)。
    2. aux 自己就塞不下 → 硬性失敗(不產生必定 OOM 的設定)。
    3. main 與 aux 同卡時,從 main 預算扣掉同卡 aux。
    4. CPU-MoE 模式:從 GGUF tensor table 拆出 experts(RAM)與 dense+KV(GPU),兩邊都 gate。
    5. 一般模式:MoE 放不下時拒絕隱性 CPU-MoE；dense 才可退到 --fit layer offload,
       並另外檢查 RAM。共卡時把 fit-target 抬高到「同卡 aux + 保留」。
    `--ignore-capacity` 可把硬性失敗降為警告(進階者自負)。
    回傳 (main 是否整顆塞得下, 建議 fit_target)。
    """
    budget = {gpu.index: gpu.total_mib - GPU_RESERVE_MIB for gpu in plan.gpus}
    aux_by_gpu: dict[int, int] = {}
    aux_details_by_gpu: dict[int, list[tuple[Selection, int]]] = {}
    for selection in (plan.embedding, plan.reranker, plan.vl):
        need = _aux_need_mib(selection, plan.reranker_ctx)
        aux_by_gpu[selection.gpu.index] = aux_by_gpu.get(selection.gpu.index, 0) + need
        aux_details_by_gpu.setdefault(selection.gpu.index, []).append((selection, need))

    for index, need in sorted(aux_by_gpu.items()):
        details = aux_details_by_gpu[index]
        notes.append(
            f"附屬容量預估:GPU {index} "
            + " + ".join(
                (
                    f"reranker(ctx={plan.reranker_ctx})~{role_need} MiB"
                    if selection.role == "reranker"
                    else f"{selection.role}~{role_need} MiB"
                )
                for selection, role_need in details
            )
            + f" = {need} MiB。"
        )
        if need > budget.get(index, 0):
            qwen_hint = ""
            if any(_is_qwen3_reranker(selection) for selection, _ in details):
                buffer_mib = _aux_overhead_mib(plan.reranker, plan.reranker_ctx)
                qwen_hint = (
                    f" 偵測到 Qwen3-Reranker：所選 ctx={plan.reranker_ctx} 的 runtime "
                    f"buffer 保守估約 {buffer_mib} MiB。若每筆 query+passage 放得下，"
                    "可降低 --rerank-ctx；也可改用 bge-reranker-v2-m3 Q8_0，"
                    "或把 reranker/VL 分到其他 GPU。"
                )
            message = (
                f"容量判定不通過:三顆附屬模型在 GPU {index} 需要約 {need} MiB,"
                f"但該卡預算只有 {budget.get(index, 0)} MiB(總 VRAM − 保留 {GPU_RESERVE_MIB})。"
                "請把附屬模型分到別的 GPU(--advanced / --embed-gpu 等),或換較小的附屬模型。"
                + qwen_hint
            )
            _capacity_problem(message, ignore, notes)

    main_index = plan.main.gpu.index
    main_aux = aux_by_gpu.get(main_index, 0)
    remaining = budget.get(main_index, 0) - main_aux
    main_need = _main_need_mib(plan.main.candidate, plan.ctx)
    fits = main_need <= remaining
    shared = "(與附屬模型共卡)" if main_aux else ""
    notes.append(
        f"容量預估:GPU {main_index} 預算 {budget.get(main_index, 0)} MiB{shared},"
        f"同卡附屬約 {main_aux} MiB,主模型含 KV/buffer 約需 {main_need} MiB → "
        + ("整顆塞得下" if fits else "塞不下(需要 CPU offload)")
    )
    planned_main_gpu = main_need if fits else max(remaining, 0)

    if plan.cpu_moe:
        layout = plan.main_layout
        if layout is None:
            _capacity_problem(
                "容量判定不通過:CPU-MoE 模式無法解析主模型 GGUF tensor table，"
                "因此無法估算 experts 的 RAM 與 dense/KV 的 VRAM。",
                ignore,
                notes,
            )
        elif not layout.is_moe:
            _capacity_problem(
                "容量判定不通過:CPU-MoE 模式未在主模型偵測到 expert tensors；"
                "--cpu-moe 對 dense 模型無效，請改用一般模式。",
                ignore,
                notes,
            )
        else:
            dense_bytes = max(plan.main.candidate.total_bytes - layout.expert_bytes, 0)
            cpu_moe_gpu_need = _main_need_for_weights_mib(dense_bytes, plan.ctx)
            planned_main_gpu = cpu_moe_gpu_need
            notes.append(
                f"CPU-MoE 容量預估:experts 約 {layout.expert_bytes / GIB:.1f} GiB 放 RAM；"
                f"dense/其他權重 + KV/buffer 在 GPU {main_index} 約需 {cpu_moe_gpu_need} MiB，"
                f"該卡扣除同卡附屬後剩 {remaining} MiB。"
            )
            if cpu_moe_gpu_need > remaining:
                _capacity_problem(
                    "容量判定不通過:即使把全部 MoE experts 放 CPU，主模型的 dense/其他權重"
                    f" + KV/buffer 仍約需 {cpu_moe_gpu_need} MiB VRAM，但 GPU {main_index}"
                    f" 只剩 {remaining} MiB。請降低 --ctx、移走同卡附屬模型，或換更大 GPU。",
                    ignore,
                    notes,
                )
            _check_system_ram(layout.expert_bytes, "CPU-MoE expert resident", ignore, notes)
    elif not fits:
        layout = plan.main_layout
        if layout is None:
            _capacity_problem(
                "容量判定不通過:主模型放不進 GPU，且無法解析 GGUF tensor table 判斷"
                " dense/MoE；拒絕猜測 CPU placement。請確認模型檔完整。",
                ignore,
                notes,
            )
        elif layout.is_moe:
            _capacity_problem(
                "容量判定不通過:這是 MoE 主模型且整顆放不進所選 GPU；一般模式不允許"
                " --fit 隱性決定 expert placement。請改用 CPU-MoE 模式(--cpu-moe)。",
                ignore,
                notes,
                # 互動流程接到這個型別會就地詢問「改用 CPU-MoE?」,不必整段重來。
                exc_type=CapacityModeError,
            )
        if not fit_supported:
            _capacity_problem(
                "容量判定不通過:主模型放不下所選 GPU，而 llama-server 不支援 --fit"
                "(dense layer 自動 GPU/CPU 配置)。請更新 llama.cpp 或換較小主模型。",
                ignore,
                notes,
            )
        _check_system_ram(
            plan.main.candidate.total_bytes,
            "一般模式 dense CPU offload(保守以上限整顆 GGUF 計)",
            ignore,
            notes,
        )

    fit_target = fit_target_arg
    if not fits and not plan.cpu_moe and main_aux:
        # 共卡時 --fit 要多留出同卡附屬模型的空間,否則 main 自動吃滿後 aux 起不來。
        raised = main_aux + GPU_RESERVE_MIB
        if raised > fit_target:
            fit_target = raised
            notes.append(
                f"主模型與附屬模型共用 GPU {main_index} → --fit-target 自動抬高到 "
                f"{fit_target} MiB(同卡附屬 {main_aux} + 保留 {GPU_RESERVE_MIB})。"
            )

    # 建議性提醒:規劃用「總 VRAM」;當下 free 不足通常是舊 server / 其他程式還占著。
    for gpu in plan.gpus:
        planned = aux_by_gpu.get(gpu.index, 0)
        if gpu.index == main_index:
            planned += min(planned_main_gpu, max(remaining, 0))
        if planned and gpu.free_mib < planned:
            notes.append(
                f"⚠ GPU {gpu.index} 目前只剩 {gpu.free_mib} MiB free(規劃需 ~{planned} MiB):"
                "有其他程式或舊 CodeTrail server 佔用,啟動前先釋放(~/start.sh stop)。"
            )
    return fits, fit_target


def recommend_main(plan_gpu: Gpu, candidate: ModelCandidate, ctx: int, threads: int,
                   fit_target: int, fit_supported: bool, fits_in_budget: bool,
                   cpu_moe: bool, notes: list[str]) -> tuple[dict, int, int]:
    """依容量規劃結果(fits_in_budget 來自 plan_capacity)決定 offload 策略與 batch。"""
    parameters: dict = {
        "jinja": True,
        "flash_attention": "on",
        "cache_type_k": "q8_0",
        "cache_type_v": "q8_0",
        "threads": threads,
    }
    if cpu_moe:
        # --fit 會嘗試改寫 tensor placement，不能和顯式 --cpu-moe override 混用。
        parameters.update({"gpu_layers": 99, "cpu_moe": True})
        if fit_supported:
            parameters["fit"] = "off"
        batch, ubatch = 1024, 256
        notes.append(
            f"主模型 {candidate.total_bytes / GIB:.0f} GB 採 CPU-MoE 模式 → "
            "全部 expert tensors 固定在 RAM(--cpu-moe)，dense/其他層全 GPU offload(-ngl 99)；"
            "只影響 main。"
        )
    elif fits_in_budget:
        parameters["gpu_layers"] = 99
        if fit_supported:
            # 新版 llama.cpp 的 --fit 預設可能是 on；明確關閉才不會重寫已規劃的 -ngl 99。
            parameters["fit"] = "off"
        batch, ubatch = 2048, 512
        notes.append(
            f"主模型 {candidate.total_bytes / GIB:.0f} GB 可整顆放進 "
            f"{plan_gpu.name}(含同卡附屬與 KV/buffer 預估)→ 全 GPU offload(-ngl 99)。"
        )
    else:
        batch, ubatch = 1024, 256
        if fit_supported:
            parameters.update(
                {"gpu_layers": "auto", "fit": "on", "fit_target": fit_target, "parallel": 1}
            )
            notes.append(
                f"主模型 {candidate.total_bytes / GIB:.0f} GB 放不下 {plan_gpu.name} 的可用預算 → "
                f"用 llama.cpp 自動配置(-ngl auto --fit on --fit-target {fit_target}),"
                "由 server 自行決定 GPU/CPU 層分配。"
            )
        else:
            # 只有 --ignore-capacity 才會走到這裡(plan_capacity 已警告過)。
            parameters["gpu_layers"] = 99
            notes.append(
                "⚠ 主模型大於可用 VRAM 且無 --fit,仍依 --ignore-capacity 產生 -ngl 99 設定"
                "(預期會 OOM,風險自負)。"
            )
    # schema 規定 ubatch ≤ batch ≤ ctx;小 ctx(CLI 允許到 1024)不夾限的話,
    # 使用者答完全部問題才會被自己的驗證打死。
    batch = min(batch, ctx)
    ubatch = min(ubatch, batch)
    mem_total = _mem_total_bytes()
    if mem_total and mem_total > candidate.total_bytes + 32 * GIB:
        parameters["no_mmap"] = True
        notes.append("系統 RAM 足夠 → 加 --no-mmap(啟動載入較慢,但首次回應不再等 page-in)。")
    else:
        notes.append("系統 RAM 不寬裕 → 不加 --no-mmap(維持 mmap 懶載入,首次回應可能較慢)。")
    notes.append("取樣參數(temp/top-p/top-k)刻意不寫死:各模型官方建議不同,"
                 "需要時自行加進 ~/.config/codetrail/deployment.json 的 services.main.parameters。")
    return parameters, batch, ubatch


def sanitize_registry_key(path: Path) -> str:
    """檔名 → 合法 registry key(deployment_profile 的 _BARE_MODEL_RE:不含底線)。"""
    stem = _SHARD_RE.match(path.name)
    name = stem.group("stem") if stem else path.stem
    key = re.sub(r"[^A-Za-z0-9.+:-]+", "-", name).strip("-").lower()
    key = re.sub(r"-{2,}", "-", key)
    if not key or not key[0].isalnum():
        key = f"model-{key.lstrip('-.')}" if key else "main-model"
    return key[:64]


