def _candidate_from_path(path: Path) -> ModelCandidate:
    """使用者直接給路徑時也要正確聚合多 shard 的總大小,並驗證齊全性。"""
    issues = _shard_issues(path)
    if issues:
        raise SetupError(f"{path.name} 不完整:" + ";".join(issues))
    shard = _shard_info(path)
    if shard:
        first, total_bytes, shards = shard
        return ModelCandidate(path=first, total_bytes=total_bytes, shards=shards)
    return ModelCandidate(path=path, total_bytes=path.stat().st_size, shards=1)


def _input(prompt: str) -> str:
    try:
        return input(prompt)
    except EOFError as exc:
        raise SetupError(
            "無互動輸入環境。請加 --yes 並用旗標提供所有必要值"
            "(--main-model/--ctx/...),見 ./set_config.sh --help。"
        ) from exc


def _input_optional(prompt: str, default: str = "") -> str:
    """非必要的收尾提問:沒有互動輸入(EOF)時採預設值,不中斷流程。"""
    try:
        return input(prompt)
    except EOFError:
        return default


def choose_candidate(
    role_label: str,
    entries: list[ModelCandidate],
    override: str | None,
    assume_yes: bool,
    *,
    flag_name: str,
) -> ModelCandidate:
    """模型選擇:沒有預設值。唯一候選自動選用;多候選必須輸入編號或路徑。"""
    if override is not None:
        if override.isdecimal():
            if not entries:
                raise SetupError(
                    f"{role_label}:掃描不到任何候選,無法用編號 {override} 指定;"
                    "請改給 .gguf 絕對路徑。"
                )
            pick = int(override)
            if not 1 <= pick <= len(entries):
                raise SetupError(
                    f"{role_label}:選項編號 {pick} 不在 {_range(1, len(entries))}。"
                )
            return entries[pick - 1]
        path = Path(override).expanduser()
        if not path.is_file() or path.suffix.lower() != ".gguf":
            raise SetupError(f"{role_label}:{override} 不是存在的 .gguf 檔。")
        return _candidate_from_path(path)
    if len(entries) == 1:
        print(f"{role_label} 只有一個候選,自動選用:{entries[0].describe()}")
        return entries[0]
    if assume_yes:
        raise SetupError(
            f"{role_label}:有 {len(entries)} 個候選;--yes 模式需要用 {flag_name} "
            f"指定編號({_range(1, len(entries))})或 .gguf 絕對路徑。"
        )

    span = _range(1, len(entries))
    print(f"\n{role_label} — 偵測到的候選:")
    for pos, cand in enumerate(entries, start=1):
        print(f"  [{pos}] {cand.describe()}")
    while True:
        raw = _input(f"請輸入編號 {span}(或直接貼 .gguf 絕對路徑): ").strip()
        if raw.isdecimal():
            if 1 <= int(raw) <= len(entries):
                return entries[int(raw) - 1]
            print(f"  無效輸入:{raw}(編號只有 {span})")
            continue
        path = Path(raw).expanduser()
        if raw and path.is_file() and path.suffix.lower() == ".gguf":
            return _candidate_from_path(path)
        print(f"  無效輸入:{raw!r}(要嘛編號 {span},要嘛存在的 .gguf 路徑)")


def choose_gpu(
    role_label: str,
    gpus: list[Gpu],
    override: str | None,
    assume_yes: bool,
    *,
    flag_name: str,
) -> Gpu:
    """GPU 選擇:沒有預設值。單卡自動選用;多卡必須輸入偵測到的 index。"""
    by_index = {gpu.index: gpu for gpu in gpus}
    if override is not None:
        if not override.isdecimal() or int(override) not in by_index:
            raise SetupError(
                f"{role_label}:GPU index '{override}' 不在偵測結果中"
                f"(可用:{sorted(by_index)})。"
            )
        return by_index[int(override)]
    if len(gpus) == 1:
        return gpus[0]
    if assume_yes:
        raise SetupError(
            f"{role_label}:偵測到多顆 GPU;--yes 模式需要用 {flag_name} 指定 GPU index"
            f"(可用:{sorted(by_index)})。"
        )

    print(f"\n{role_label} — 要放哪顆 GPU?")
    for gpu in gpus:
        print(f"  [{gpu.index}] {gpu.describe()}")
    while True:
        raw = _input(f"請輸入 GPU index(可用:{sorted(by_index)}): ").strip()
        if raw.isdecimal() and int(raw) in by_index:
            return by_index[int(raw)]
        print(f"  無效的 GPU index:{raw!r}(可用:{sorted(by_index)})")


def choose_int(label: str, override: int | None, assume_yes: bool, *,
               minimum: int, maximum: int, flag_name: str,
               hints: tuple[str, ...] = ()) -> int:
    """數值輸入:沒有預設值,只驗證範圍(選項外的輸入會重問)。

    互動與旗標共用同一組上下限:互動不得寫入 CLI/schema 明令拒絕的值。
    hints 只是輸入前的口頭提醒(越大越吃顯存之類),不影響任何驗證——
    本工具不用估算擋輸入,能不能塞下以啟動後 nvidia-smi 實測為準。
    """
    span = _range(minimum, maximum)
    if override is not None:
        if not minimum <= override <= maximum:
            raise SetupError(f"{label} 必須在 {span}。")
        return override
    if assume_yes:
        raise SetupError(f"--yes 模式需要用 {flag_name} 指定 {label}({span})。")
    for hint in hints:
        print(f"  {hint}")
    while True:
        raw = _input(f"{label}({span}): ").strip()
        if raw.isdecimal() and minimum <= int(raw) <= maximum:
            return int(raw)
        print(f"  無效輸入:請輸入 {span} 的整數。")


