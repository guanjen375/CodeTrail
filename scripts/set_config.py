def _pip_fix_hint(python_bin: str) -> str:
    """缺依賴時可直接複製的修復指令;venv 的 pip 會拒絕 --user,兩種環境分開建議。"""
    requirements = REPO_ROOT / "requirements.txt"
    if sys.prefix != getattr(sys, "base_prefix", sys.prefix):
        return (
            f"{python_bin} -m pip install -r {requirements}\n"
            "  (這顆 Python 在 venv 內:直接裝進 venv,不要加 --user)"
        )
    return (
        f"{python_bin} -m pip install --user --break-system-packages -r {requirements}\n"
        "  (或先 activate 你的 venv 再重跑 ./set_config.sh)"
    )


def _detect_python(skip_deps_check: bool, notes: list[str]) -> str:
    """MCP server 要跑在哪個 Python:用執行 set_config 的這一顆,並驗證依賴齊全。

    把絕對路徑寫死進 opencode.json 的 MCP command,新 shell 不 activate venv
    也能啟動 MCP server(舊安裝流程最常踩的坑)。
    """
    python_bin = sys.executable or "python3"
    try:
        proc = subprocess.run(
            [python_bin, "-c", "import mcp, numpy, requests"],
            capture_output=True,
            text=True,
            check=False,
            timeout=60,
        )
    except subprocess.TimeoutExpired as exc:
        message = (
            f"Python 依賴檢查逾時(60 秒):{python_bin}\n"
            "  可能是 NFS/磁碟卡住或 site-packages 損壞;"
            "先在終端手動執行一次上述 Python 確認,再重跑 ./set_config.sh"
        )
        if skip_deps_check:
            notes.append("⚠ 已用 --skip-deps-check 跳過依賴檢查:" + message)
            return python_bin
        raise SetupError("[FAIL] " + message) from exc
    if proc.returncode != 0:
        message = (
            f"這顆 Python({python_bin})缺少 CodeTrail 依賴(mcp/numpy/requests)。\n"
            f"  修復:{_pip_fix_hint(python_bin)}"
        )
        if skip_deps_check:
            notes.append("⚠ 已用 --skip-deps-check 跳過依賴檢查:" + message)
        else:
            raise SetupError("[FAIL] Python 依賴檢查未通過:\n" + message)
    return python_bin


def _check_tmux(skip: bool, notes: list[str]) -> None:
    if shutil.which("tmux"):
        return
    message = (
        "[FAIL] 找不到 tmux(啟動器用它把四個 server 放到背景)。\n"
        "  Ubuntu / Debian 修復:sudo apt install -y tmux\n"
        "  修復後重新執行:./set_config.sh"
    )
    if skip:
        notes.append("⚠ 已用 --skip-binary-check 跳過 tmux 檢查。")
        return
    raise SetupError(message)


def _llama_bin() -> Path:
    """LLAMA_BIN 一律轉成絕對路徑:相對路徑在這裡驗證會過(對 set_config 的 cwd),
    但寫進 ~/start.sh 後從別的目錄執行就找不到 binary。"""
    raw = os.environ.get("LLAMA_BIN")
    if raw:
        return Path(os.path.abspath(os.path.expanduser(raw)))
    return Path.home() / "llama.cpp" / "build" / "bin" / "llama-server"


def check_llama_binary(skip: bool, notes: list[str]) -> dict[str, bool]:
    """llama-server 存在性 + 必要旗標探測;回傳已驗證 capabilities。"""
    binary = _llama_bin()
    if not binary.is_file() or not os.access(binary, os.X_OK):
        message = (
            f"[FAIL] 找不到可執行的 llama-server:{binary}\n"
            "  尚未 build 的話照 README §1.5:\n"
            "    git clone https://github.com/ggerganov/llama.cpp ~/llama.cpp\n"
            "    cd ~/llama.cpp && cmake -B build -DGGML_CUDA=ON -DLLAMA_CURL=OFF && "
            "cmake --build build --config Release -j\n"
            "  放在別處的話:export LLAMA_BIN=/path/to/llama-server 後重跑 ./set_config.sh"
        )
        if skip:
            notes.append("⚠ 已用 --skip-binary-check 跳過 llama-server 檢查(假設為支援 --fit 的新版)。")
            return {"fit": True, "cpu_moe": True, "n_cpu_moe": True, "cache_ram": True}
        raise SetupError(message)
    try:
        proc = subprocess.run(
            [str(binary), "--help"], capture_output=True, text=True, timeout=30, check=False
        )
        help_text = proc.stdout + proc.stderr
    except (OSError, subprocess.TimeoutExpired) as exc:
        # 連 --help 都跑不動的 binary 不能假定支援任何旗標:非明確 skip 一律硬停,
        # 否則會在 [2/5] 顯示 PASS、到 ~/start.sh 才發現整組啟動不了。
        message = (
            f"[FAIL] llama-server --help 無法執行:{binary}\n"
            f"    {exc}\n"
            "  可能是 binary 損壞、架構不符或執行環境問題(動態庫/權限)。\n"
            f"  先在終端執行 {binary} --help 確認,再重跑 ./set_config.sh"
        )
        if skip:
            notes.append(
                "⚠ 已用 --skip-binary-check 跳過 llama-server 執行檢查"
                f"(--help 無法執行:{exc};假設支援全部旗標)。"
            )
            return {"fit": True, "cpu_moe": True, "n_cpu_moe": True, "cache_ram": True}
        raise SetupError(message) from exc

    # --help 跑不起來(常見:動態庫找不到)時,help_text 是 loader 錯誤而不是旗標清單。
    # 這種情況不能誤診成「build 不支援 --reranking」,要指向真正的執行環境問題。
    recognized = any(
        flag in help_text for flag in ("--reranking", "--mmproj", "--fit", "--port", "usage:")
    )
    if proc.returncode != 0 and not recognized:
        detail = "\n    ".join(
            line for line in (proc.stderr or proc.stdout).strip().splitlines()[:5]
        )
        message = (
            f"[FAIL] llama-server 無法執行(--help 失敗,exit {proc.returncode}):{binary}\n"
            f"    {detail or '(無輸出)'}\n"
            "  這通常不是旗標支援問題,而是執行環境問題:\n"
            "  - 動態庫找不到(例如 libcudart / libcublas):把 CUDA lib 目錄加進 LD_LIBRARY_PATH\n"
            "  - binary 損壞或架構不符:重新 build llama.cpp(README §1.5)\n"
            f"  修好後先在終端執行 {binary} --help 確認,再重跑 ./set_config.sh"
        )
        if skip:
            notes.append("⚠ 已用 --skip-binary-check 跳過 llama-server 執行檢查(--help 失敗)。")
            return {"fit": True, "cpu_moe": True, "n_cpu_moe": True, "cache_ram": True}
        raise SetupError(message)

    missing = [flag for flag in ("--reranking", "--mmproj") if flag not in help_text]
    if missing:
        message = (
            f"[FAIL] 這個 llama-server 不支援 {' / '.join(missing)}"
            "(reranker / VL 角色必要)。\n"
            "  修復:更新並重新 build llama.cpp(README §1.5):\n"
            "    cd ~/llama.cpp && git pull && rm -rf build && "
            "cmake -B build -DGGML_CUDA=ON -DLLAMA_CURL=OFF && cmake --build build --config Release -j"
        )
        if skip:
            notes.append("⚠ 已跳過 llama-server 旗標檢查:" + " / ".join(missing) + " 不支援。")
        else:
            raise SetupError(message)
    caps = {
        "fit": bool(re.search(r"(?<![\w-])--fit(?![\w-])", help_text)),
        # 不把 --cpu-moe-draft 誤認成主模型用的 --cpu-moe。
        "cpu_moe": bool(re.search(r"(?<![\w-])--cpu-moe(?![\w-])", help_text)),
        # 手動 n_cpu_moe(部分 experts 留 GPU)寫入前先確認 build 支援。
        "n_cpu_moe": bool(re.search(r"(?<![\w-])--n-cpu-moe(?![\w-])", help_text)),
        # 非生成服務的 prompt cache 不可重用，兩角色固定傳 0 防止 RAM 線性成長。
        "cache_ram": bool(re.search(r"(?<![\w-])--cache-ram(?![\w-])", help_text)),
    }
    if not caps["cache_ram"]:
        message = (
            "[FAIL] embedding / reranker 的安全預設需要 llama-server --cache-ram，"
            "才能以 --cache-ram 0 停用不可重用、會累積 RAM 的 prompt cache；"
            "這個 build 不支援該旗標。\n"
            "  修復:更新並重新 build llama.cpp(README §1.5)，再重跑 ./set_config.sh"
        )
        if skip:
            notes.append("⚠ 已跳過 --cache-ram 檢查(假設為支援該旗標的新版)。")
            caps["cache_ram"] = True
        else:
            raise SetupError(message)
    if not caps["fit"]:
        # VL 固定用 --fit 在 embedding/reranker 啟動後保留推論 VRAM,這是硬需求。
        # 在前置檢查就擋下,不讓使用者答完所有互動題才發現白忙一場。
        message = (
            "[FAIL] 安全的 VL placement 需要 llama-server --fit,才能在 embedding/reranker"
            " 啟動後保留推論用 VRAM;這個 build 不支援 --fit。\n"
            "  修復:更新並重新 build llama.cpp(README §1.5):\n"
            "    cd ~/llama.cpp && git pull && rm -rf build && "
            "cmake -B build -DGGML_CUDA=ON -DLLAMA_CURL=OFF && cmake --build build --config Release -j"
        )
        if skip:
            notes.append("⚠ 已跳過 --fit 檢查(假設為支援 --fit 的新版)。")
            caps["fit"] = True
        else:
            raise SetupError(message)
    ldd = shutil.which("ldd")
    if ldd:
        link = subprocess.run([ldd, str(binary)], capture_output=True, text=True, check=False)
        if link.returncode == 0 and "cuda" not in link.stdout.lower():
            notes.append("⚠ llama-server 看起來是純 CPU build(未連結 CUDA);能跑但會非常慢。")
    return caps


def detect_gpus() -> list[Gpu]:
    smi = shutil.which("nvidia-smi")
    if not smi:
        raise SetupError(
            "偵測失敗:找不到 nvidia-smi。請確認 NVIDIA 驅動已安裝,"
            "且 nvidia-smi 在 PATH 上(README §1)。"
        )
    try:
        proc = subprocess.run(
            [smi, "--query-gpu=index,name,memory.total,memory.free,uuid",
             "--format=csv,noheader,nounits"],
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except subprocess.TimeoutExpired as exc:
        raise SetupError(
            "偵測失敗:nvidia-smi 執行逾時(30 秒)。GPU driver 可能卡住:"
            "先在終端手動執行 nvidia-smi 確認,必要時重載驅動或重開機後重跑。"
        ) from exc
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()
        raise SetupError(f"偵測失敗:nvidia-smi 執行失敗:{detail or '無輸出'}")
    gpus: list[Gpu] = []
    for line in proc.stdout.splitlines():
        parts = [part.strip() for part in line.split(",")]
        if len(parts) < 5 or not parts[0].isdecimal():
            continue
        try:
            total = int(parts[2])
            free = int(parts[3])
        except ValueError:
            total, free = 0, 0
        gpus.append(Gpu(index=int(parts[0]), name=parts[1], total_mib=total,
                        free_mib=free, uuid=parts[4]))
    if not gpus:
        raise SetupError("偵測失敗:nvidia-smi 沒有回報任何可用的 NVIDIA GPU。")
    return gpus


