def _fresh_env(plan: Plan) -> dict[str, str]:
    env = {key: value for key, value in os.environ.items() if key not in _OVERRIDE_ENV_KEYS}
    env["AICODE_MODEL"] = plan.main_key
    return env


def _sanitized_subprocess_env() -> dict[str, str]:
    """啟停子程序用的乾淨環境:同 ~/start.sh 開頭的 unset(override + session 名)。

    stop_servers / start.sh 必須看到同一組「預設」session 名;桌面環境常見的泛用
    SESSION 變數若流進 stop_servers,會殺錯無關的 tmux session、漏掉真正的
    codetrail-rag,接著重啟就撞 session already exist。
    """
    return {
        key: value for key, value in os.environ.items()
        if key not in _OVERRIDE_ENV_KEYS and key not in _SESSION_ENV_KEYS
    }


def _restart_servers(start_path: Path) -> int:
    """[R] 自動重啟:先 quit 再 start,兩者都用 sanitized env。"""
    env = _sanitized_subprocess_env()
    subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "stop_servers.py"), "--scope", "all"],
        check=False,
        env=env,
    )
    print("  已停止舊 server;開始啟動新設定(載入大模型需要幾分鐘)…")
    return subprocess.run(["bash", str(start_path)], check=False, env=env).returncode


def validate_payloads(plan: Plan, deployment_json: str, registry_json: str) -> None:
    """寫入正式檔之前,用 staging 內容跑一次 deployment_profile 完整驗證。"""
    env = _fresh_env(plan)
    env["AICODE_MODEL_REGISTRY"] = registry_json
    tmp = tempfile.NamedTemporaryFile(
        "w", suffix=".json", prefix="codetrail-setconfig-", delete=False, encoding="utf-8"
    )
    try:
        tmp.write(deployment_json)
        tmp.close()
        env["AICODE_DEPLOYMENT_CONFIG"] = tmp.name
        load_effective_profile(env)
    except ProfileError as exc:
        raise SetupError(f"產生的設定未通過 deployment profile 驗證(未寫入任何檔案):{exc}") from exc
    finally:
        Path(tmp.name).unlink(missing_ok=True)


def preview_start_commands(plan: Plan) -> int:
    """跑 launch_servers.py --scope all --dry-run,把最終 llama-server 指令(推薦參數)印給使用者。"""
    env = _fresh_env(plan)
    env["MAIN_GPU"] = plan.main.gpu.selector
    env["EMBED_GPU"] = plan.embedding.gpu.selector
    env["RERANK_GPU"] = plan.reranker.gpu.selector
    env["VL_GPU"] = plan.vl.gpu.selector
    try:
        proc = subprocess.run(
            [sys.executable, str(REPO_ROOT / "scripts" / "launch_servers.py"),
             "--scope", "all", "--dry-run"],
            env=env,
            capture_output=True,
            text=True,
            check=False,
            timeout=120,
        )
    except subprocess.TimeoutExpired:
        print("⚠ 啟動參數預覽逾時(120 秒);設定檔已寫入,可直接用 ~/start.sh --dry-run 重試預覽。",
              file=sys.stderr)
        return 1
    print("\n=== 推薦啟動參數(~/start.sh 實際會執行的指令)===")
    if proc.stdout:
        print(proc.stdout, end="")
    if proc.returncode != 0:
        print(proc.stderr, end="", file=sys.stderr)
        print("⚠ 啟動參數預覽失敗(見上方訊息);請修正後重跑 ./set_config.sh。",
              file=sys.stderr)
    return proc.returncode


def running_codetrail_sessions() -> list[str]:
    if not shutil.which("tmux"):
        return []
    # 探測「env 指定名 ∪ 預設名」:~/start.sh 內部會 unset session env 再啟動,
    # 實際 session 幾乎都是預設名;桌面環境把通用變數 SESSION 設走時,
    # 只看 env 會漏掉真正在跑的 codetrail-rag。
    names: list[str] = []
    for name in (
        os.environ.get("MAIN_SESSION"), "codetrail-main",
        os.environ.get("SESSION"), os.environ.get("AUX_SESSION"), "codetrail-rag",
    ):
        if name and name not in names:
            names.append(name)
    running = []
    for name in names:
        probe = subprocess.run(
            ["tmux", "has-session", "-t", name],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
        if probe.returncode == 0:
            running.append(name)
    return running


