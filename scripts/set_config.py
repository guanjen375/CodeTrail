#!/usr/bin/env python3
"""CodeTrail 一鍵設定精靈(`./set_config.sh` 的實作)。

純問答式設定:不用估算限制或推薦任何數值(CPU-MoE 那題會依 GGUF 權重與
nvidia-smi 的 free VRAM 給參考端點,但不擋輸入);使用者選擇題由
使用者作答,工具只驗證輸入在合理範圍(例如選項只有 1-2 卻輸入 3 會重問)。
VRAM 塞不塞得下以啟動後實測為準(產生的 ~/start.sh 啟動完會提醒用
nvidia-smi 稍微監控)。

  1. 前置檢查:Python 依賴、tmux、nvidia-smi、llama-server 與必要旗標
     (--reranking / --mmproj / --fit / --cache-ram),缺什麼就給可直接複製的修復指令。
  2. 偵測:GPU 種類/VRAM、~/models 的 GGUF 自動分類(main / embedding /
     reranker / VL+mmproj);多 shard 聚合並驗證齊全性(缺片直接列出)。
  3. 背景初步判定:GPU 數與四類模型是否齊全,缺什麼通知什麼。
  4. 互動問答,一個角色問完才進下一個(每組先列出偵測結果再提問):
       [1/4] 主聊天模型 → 模型、GPU、ctx、CPU-MoE 層數
       [2/4] embedding  → 模型、GPU
       [3/4] reranker   → 模型、GPU、internal buffer(ctx)
       [4/4] VL         → 模型、GPU、mmproj、CPU-MoE 層數
     CPU-MoE 沒有 y/n 分流:直接問層數,0 = 不 offload(一般模式)、
     N = 前 N 層 experts 留 RAM、≥ 層數上限 = 全部留 RAM(等同 --cpu-moe);
     模型不是 MoE(GGUF 沒有 expert tensors)時直接略過並印出原因。
     只有一個候選(或一顆 GPU)時自動選用;其餘必答。
     threads 不再是問題:未給 --threads 就不寫 -t,交給 llama.cpp 自己的預設。
     最後顯示摘要一頁(Enter 寫入 / q 離開)。
  5. 非互動:`--yes` 跳過提問與確認,但所有使用者選擇題的值必須由旗標提供
     (--main-model / --ctx / --rerank-ctx / ...),缺哪個就明確報錯。
  6. 產物(先寫 staging、全部就緒才原子替換;既有檔備份 *.bak-setconfig-*):
     - ~/.config/codetrail/models.json     主模型 registry(合併既有)
     - ~/.config/codetrail/deployment.json deployment local override
     - ~/.config/opencode/opencode.json    只合併 CodeTrail 管的欄位,
                                           保留使用者既有 provider / mcp / 其他設定
     - ~/start.sh                          啟動腳本(支援 status / stop / logs 子命令)
  7. 安全預設:llama-server 只綁 127.0.0.1;要讓其他機器連線必須明確
     `--allow-remote`(或 deployment.json 的 bind: "all-interfaces")。

`--restore-last-backup` 可把四個產物還原到最近一次備份。
純 stdlib;不 eval / source 任何內容;產物經 deployment_profile 的封閉 schema 驗證。
"""
