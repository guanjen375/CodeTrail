def _pip_fix_hint(python_bin: str) -> str:
    """缺依賴時可直接複製的修復指令;venv 的 pip 會拒絕 --user,兩種環境分開建議。"""
    requirements = REPO_ROOT / "requirements.txt"
    if sys.prefix != getattr(sys, "base_prefix", sys.prefix):
        return (
            f"{python_bin} -m pip install -r {requirements}\n"
            "  (這顆 Python 在 venv 內:直接裝進 venv,不要加 --user)"
        )
    return (
        f"{python_bin} -m pip install --user --break-system-packages -r {requirements}\n"
        "  (或先 activate 你的 venv 再重跑 ./set_config.sh)"
    )


def _detect_python(skip_deps_check: bool, notes: list[str]) -> str:
    """MCP server 要跑在哪個 Python:用執行 set_config 的這一顆,並驗證依賴齊全。

    把絕對路徑寫死進 opencode.json 的 MCP command,新 shell 不 activate venv
    也能啟動 MCP server(舊安裝流程最常踩的坑)。
    """
    python_bin = sys.executable or "python3"
    try:
        proc = subprocess.run(
            [python_bin, "-c", "import mcp, numpy, requests"],
            capture_output=True,
            text=True,
            check=False,
            timeout=60,
        )
    except subprocess.TimeoutExpired as exc:
        message = (
            f"Python 依賴檢查逾時(60 秒):{python_bin}\n"
            "  可能是 NFS/磁碟卡住或 site-packages 損壞;"
            "先在終端手動執行一次上述 Python 確認,再重跑 ./set_config.sh"
        )
        if skip_deps_check:
            notes.append("⚠ 已用 --skip-deps-check 跳過依賴檢查:" + message)
            return python_bin
        raise SetupError("[FAIL] " + message) from exc
    if proc.returncode != 0:
        message = (
            f"這顆 Python({python_bin})缺少 CodeTrail 依賴(mcp/numpy/requests)。\n"
            f"  修復:{_pip_fix_hint(python_bin)}"
        )
        if skip_deps_check:
            notes.append("⚠ 已用 --skip-deps-check 跳過依賴檢查:" + message)
        else:
            raise SetupError("[FAIL] Python 依賴檢查未通過:\n" + message)
    return python_bin


