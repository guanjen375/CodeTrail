def cpu_moe_layer_ceiling(layout: ModelLayout | None) -> int:
    """「全部 experts 留 RAM」的門檻:輸入 ≥ 這個值等同 --cpu-moe。"""
    layers = layout.expert_layer_bytes if layout is not None else ()
    return layers[-1][0] + 1 if layers else 1


def cpu_moe_gpu_bytes(layout: ModelLayout, n_cpu_moe: int) -> int:
    """--n-cpu-moe N 之下留在 GPU 的「權重」bytes(前 N 層 experts 移去 RAM)。"""
    on_cpu = sum(size for index, size in layout.expert_layer_bytes if index < n_cpu_moe)
    return max(0, layout.tensor_bytes - on_cpu)


def cpu_moe_fit_layers(layout: ModelLayout, budget_bytes: int) -> int | None:
    """權重剛好放得進 budget 的最小 N;連全部移到 RAM 都放不下回傳 None。"""
    ceiling = cpu_moe_layer_ceiling(layout)
    for n_cpu_moe in range(0, ceiling + 1):
        if cpu_moe_gpu_bytes(layout, n_cpu_moe) <= budget_bytes:
            return n_cpu_moe
    return None


def cpu_moe_recommendation(layout: ModelLayout, gpu: Gpu | None,
                           reserve_mib: int = 0) -> str:
    """給使用者一個可以直接照打的推薦區間,例如 "38-43"。

    下界 = 權重剛好放得進(free VRAM - reserve_mib)的最小層數;
    上界 = 全部 experts 移到 RAM(GPU 負載最低)。

    reserve_mib 是留給 KV cache / compute buffer / mmproj 的手動餘量。VL 特別需要
    它:一旦套用 CPU-MoE,llama.cpp 的 --fit 會直接放棄(見 build_vl_parameters),
    -ngl 退化成「全部層上 GPU」而沒有任何自動退讓,下界貼著權重上限就等於必 OOM。
    KV cache、compute buffer、共用同一顆卡的附屬服務仍然沒被精算,所以這是
    「從這裡開始試」的推薦,不是保證,也不拿來限制輸入(仍只驗證 0-MAX 範圍)。
    """
    ceiling = cpu_moe_layer_ceiling(layout)
    if gpu is None or not layout.expert_layer_bytes:
        # 沒有 GPU 資訊、或 expert tensors 沒有 blk 編號 → 只能推薦「全部移到 RAM」。
        return str(ceiling)
    fit = cpu_moe_fit_layers(layout, max(0, gpu.free_mib - reserve_mib) * MIB)
    if fit is None:
        return f"{ceiling}(GPU 負載已最低,這顆卡仍可能放不下)"
    if fit == 0:
        return "0(權重整顆放得進 GPU)"
    if fit >= ceiling:
        return str(ceiling)
    return f"{fit}-{ceiling}"


def choose_cpu_moe_layers(
    role_label: str,
    layout: ModelLayout | None,
    *,
    cpu_moe_override: bool | None,
    n_cpu_moe_override: int | None,
    assume_yes: bool,
    caps: dict[str, bool],
    flag_names: tuple[str, str, str],
    notes: list[str],
    gpu: Gpu | None = None,
    reserve_mib: int = 0,
) -> tuple[bool, int | None]:
    """CPU-MoE 只有一題:「幾層 experts 留 RAM」。沒有 y/n 分流、不限制輸入。

    回傳 (cpu_moe, n_cpu_moe):
      (False, None) = 不 offload,experts 全留 GPU(一般模式)
      (True, N)     = 前 N 層 experts 留 RAM(--n-cpu-moe N)
      (True, None)  = 全部 experts 留 RAM(--cpu-moe)

    非 MoE 模型(GGUF 沒有 expert tensors)不問,直接印出原因;
    build 不支援對應旗標時也不問,只留 note。
    """
    all_flag, none_flag, n_flag = flag_names
    ceiling = cpu_moe_layer_ceiling(layout)
    is_moe = layout is not None and layout.is_moe

    # --- 旗標覆寫(與互動同語意:0 = 關閉、N = 前 N 層、--cpu-moe = 全部) ---
    if cpu_moe_override is False or n_cpu_moe_override == 0:
        return False, None
    if cpu_moe_override is True:
        # GGUF 解析不出來時仍允許強制開:這是「我知道它是 MoE」的逃生門。
        if layout is not None and not is_moe:
            raise SetupError(
                f"{all_flag} 只對 MoE 模型有意義:{role_label}未偵測到 expert tensors。"
            )
        if not caps.get("cpu_moe", False):
            raise SetupError(
                f"{role_label}:全 CPU-MoE 需要 llama-server 的 --cpu-moe,"
                "但目前 build 不支援。\n"
                f"  修復:更新並重新 build llama.cpp(README §1.5),或改用 {none_flag}。"
            )
        return True, None
    if n_cpu_moe_override is not None:
        # 部分 offload 要知道層數上限才有意義:解析不出 expert tensors 就不猜。
        if not is_moe:
            raise SetupError(
                f"{n_flag} 只對 MoE 模型有意義:{role_label}未偵測到 expert tensors"
                f"(或 GGUF 無法解析);確定是 MoE 請改用 {all_flag}。"
            )
        if n_cpu_moe_override >= ceiling:
            if not caps.get("cpu_moe", False):
                raise SetupError(
                    f"{role_label}:{n_flag} {n_cpu_moe_override} ≥ 層數上限 {ceiling}"
                    " 等同全 CPU-MoE,但這個 build 不支援 --cpu-moe。\n"
                    "  修復:更新並重新 build llama.cpp(README §1.5)。"
                )
            return True, None
        if not caps.get("n_cpu_moe", False):
            raise SetupError(
                f"{role_label}:{n_flag} 需要 llama-server 支援 --n-cpu-moe,"
                "但目前 build 沒有這個旗標。\n"
                f"  修復:更新並重新 build llama.cpp(README §1.5),或改用 {all_flag}。"
            )
        return True, n_cpu_moe_override

    if layout is None:
        notes.append(
            f"⚠ 無法讀取 {role_label} 的 GGUF tensor 配置 → 不套用 CPU-MoE"
            f"(確定是 MoE 要強制啟用時用 {all_flag} / {n_flag})。"
        )
        return False, None
    if not is_moe:
        arch = f",architecture={layout.architecture}" if layout.architecture else ""
        if layout.metadata_claims_moe:
            # metadata 說有 experts、tensor 名稱卻對不上 llama.cpp 的 offload 規則:
            # 這種模型 --cpu-moe 抓不到東西,要講清楚而不是含糊說成 dense。
            notes.append(
                f"⚠ {role_label}:GGUF metadata 宣稱有 {layout.expert_count} 個 experts"
                f"({layout.architecture or '未知 architecture'}),但沒有任何 tensor 名稱符合"
                " llama.cpp 的 expert offload 規則(.ffn_(up|down|gate|gate_up)_(ch)?exps)"
                " → --cpu-moe / --n-cpu-moe 對它不會有作用,已略過提問。"
            )
        else:
            print(f"  dense 模型:GGUF 沒有 expert tensors{arch} → 略過 CPU-MoE 提問。")
        return False, None
    if not caps.get("cpu_moe", False) and not caps.get("n_cpu_moe", False):
        notes.append(
            f"⚠ {role_label}是 MoE,但這個 llama-server build 不支援 --cpu-moe/"
            "--n-cpu-moe → 不套用 CPU-MoE。更新並重新 build llama.cpp"
            "(README §1.5)後重跑可啟用。"
        )
        return False, None
    if assume_yes:
        raise SetupError(
            f"{role_label}是 MoE:--yes 模式需要用 {n_flag} N 指定留 RAM 的層數"
            f"(0 = 不 offload),或 {all_flag} / {none_flag}。"
        )

    hints = (
        "數值越大 → GPU 負載越低(0 = 不 offload)。",
        f"推薦數值:{cpu_moe_recommendation(layout, gpu, reserve_mib)}",
    )
    value = choose_int(
        f"{role_label} CPU-MoE 留在 RAM 的層數", None, False,
        minimum=0, maximum=MAX_N_CPU_MOE, flag_name=n_flag, hints=hints,
    )
    if value == 0:
        return False, None
    if value >= ceiling:
        if not caps.get("cpu_moe", False):
            notes.append(
                f"⚠ {role_label}:這個 build 不支援 --cpu-moe → 改用 "
                f"--n-cpu-moe {ceiling}(效果相同:所有帶編號的 expert 層都留 RAM)。"
            )
            return True, ceiling
        return True, None
    if not caps.get("n_cpu_moe", False):
        notes.append(
            f"⚠ {role_label}:這個 build 不支援 --n-cpu-moe(部分 offload)→ "
            "改用全 CPU-MoE(--cpu-moe);更新並重新 build llama.cpp 後可用。"
        )
        return True, None
    return True, value


def resolve_vl_mmproj(
    vl_cand: ModelCandidate,
    override: str | None,
    interactive: bool,
) -> Path:
    """mmproj 配對:唯一 → 自動;多個 → 必須選(不猜);沒有 → 停下並指路。"""
    if override:
        path = Path(override).expanduser()
        if not path.is_file() or path.suffix.lower() != ".gguf":
            raise SetupError(f"VL mmproj:{override} 不是存在的 .gguf 檔。")
        return path
    choices = list(vl_cand.mmproj_choices)
    if not choices:
        sibling = sorted(vl_cand.path.parent.glob("*mmproj*.gguf"))
        choices = sibling
    if not choices:
        raise SetupError(
            f"VL 模型 {vl_cand.path.name} 同目錄找不到 mmproj *.gguf;"
            "VL 模型與它的 mmproj 必須放在同一目錄(README §2.4),"
            "或用 --vl-mmproj 明確指定。"
        )
    if len(choices) == 1:
        return choices[0]
    if not interactive:
        listing = "、".join(p.name for p in choices)
        raise SetupError(
            f"VL 模型 {vl_cand.path.name} 同目錄有多個 mmproj({listing}),"
            "無法自動判斷相容配對(配錯會讓圖片分析輸出錯亂):"
            "請用 --vl-mmproj <絕對路徑> 明確指定,或互動重跑 ./set_config.sh 選擇。"
        )
    print(f"\n【VL mmproj】{vl_cand.path.name} 同目錄有多個 mmproj,請選擇相容的那個:")
    for pos, choice in enumerate(choices, start=1):
        print(f"  [{pos}] {choice.name}")
    while True:
        raw = _input(f"請輸入編號 {_range(1, len(choices))}: ").strip()
        if raw.isdecimal() and 1 <= int(raw) <= len(choices):
            return choices[int(raw) - 1]
        print("  無效輸入。")


