def build_models_registry(plan: Plan, registry_path: Path, notes: list[str]) -> dict:
    existing: dict = {}
    if registry_path.is_file():
        try:
            loaded = json.loads(registry_path.read_text(encoding="utf-8"))
            if isinstance(loaded, dict):
                existing = loaded
            else:
                notes.append(f"{registry_path} 不是 JSON object,將重建(原檔已備份)。")
        except (OSError, json.JSONDecodeError):
            notes.append(f"{registry_path} 無法解析,將重建(原檔已備份)。")

    # 既有項目先過 loader 同款格式驗證:一個壞 key 會讓啟動時整份 registry 被拒,
    # 與其留到 ~/start.sh 才爆,不如現在剔除並提醒(原檔有備份)。
    merged: dict = {}
    stale: list[str] = []
    for key, value in existing.items():
        valid = (
            isinstance(key, str)
            and _BARE_MODEL_RE.fullmatch(key)
            and isinstance(value, str)
            and value.strip()
        )
        if valid:
            try:
                expanded = Path(value).expanduser()
                valid = expanded.is_absolute() and expanded.suffix.lower() == ".gguf"
            except (OSError, RuntimeError):
                valid = False
        if not valid:
            notes.append(
                f"⚠ models.json 有格式不合法的項目已剔除:{key!r}"
                "(啟動時整份 registry 會因它被拒;原值在備份)"
            )
            continue
        merged[key] = value
        if key != plan.main_key and not Path(value).expanduser().is_file():
            stale.append(key)
    if stale:
        notes.append(
            "registry 內有項目指向已不存在的檔案:" + "、".join(sorted(stale))
            + "(不影響本次設定;TUI /models 殘留舊項目時可自行清理"
            " models.json 與 opencode.json 的 provider.llamacpp.models)"
        )
    merged[plan.main_key] = str(plan.main.candidate.path)
    return merged


def warn_cpu_moe_without_no_mmap(role_label: str, service_key: str, cpu_moe: bool,
                                 parameters: dict, notes: list[str]) -> None:
    """CPU-MoE + mmap 是 llama.cpp 會自己警告的組合,不能靜默放過。

    experts 留在 RAM 但檔案仍走 mmap 時,權重是「第一次推論才從 SSD 逐頁載入」,
    首次回應可能慢到分鐘級(docs/troubleshooting.md 有記載)。本工具不替使用者
    決定 no_mmap(那是使用者領域、代價是啟動時要把整份權重讀進 RAM),
    但要把選項講清楚。
    """
    if not cpu_moe or parameters.get("no_mmap"):
        return
    notes.append(
        f"⚠ {role_label} 開了 CPU-MoE 但未設 no_mmap:llama-server 會警告"
        "「tensor overrides to CPU are used with mmap enabled」,experts 要等第一次"
        "推論才從 SSD 逐頁載入,首次回應可能慢到分鐘級。要改的話手動在 "
        f"~/.config/codetrail/deployment.json 的 services.{service_key}.parameters 加 "
        '"no_mmap": true(代價:啟動時就把整份權重讀進 RAM,較慢也較吃 RAM);'
        "重跑 set_config 會保留這個設定。"
    )


def vl_uses_cpu_moe(plan: Plan) -> bool:
    return plan.vl_cpu_moe or plan.vl_n_cpu_moe is not None


def build_vl_parameters(plan: Plan) -> dict:
    """VL 服務參數。VL 固定最後啟動,所以預設讓 llama.cpp 依剩餘 VRAM 自動配置。

    沒有 CPU-MoE:-ngl auto + --fit on --fit-target,依 embedding/reranker 的實際
    占用自動決定 offload 層數(server 也會把 mmproj worst-case memory 算進去)。

    有 CPU-MoE:**--fit 不能用**。llama.cpp 的 common_params_fit_impl 一看到
    model_params::tensor_buft_overrides 已被使用者設過就直接
    「abort」(common/fit.cpp),而 --cpu-moe / --n-cpu-moe 正是往那裡塞 override。
    放棄後只印一行 WARN 就繼續載入,且 -ngl auto(-1)在 llama.h 的語意是
    「negative value means all layers」→ 退化成全部層上 GPU、完全沒有安全網。
    與其寫一組不會生效的 --fit on --fit-target 讓人誤以為有保護,不如照 main 的
    做法明寫 -ngl 99 --fit off:實際行為相同,但設定檔與啟動指令不說謊。
    """
    parameters: dict = {"parallel": AUX_PARALLEL}
    if vl_uses_cpu_moe(plan):
        parameters.update({"gpu_layers": 99, "fit": "off"})
    else:
        parameters.update({
            "gpu_layers": "auto",
            "fit": "on",
            "fit_target": VL_FIT_TARGET_MIB,
        })
    if plan.vl_n_cpu_moe is not None:
        parameters["n_cpu_moe"] = plan.vl_n_cpu_moe
    elif plan.vl_cpu_moe:
        parameters["cpu_moe"] = True
    return parameters


def build_deployment_config(plan: Plan) -> dict:
    services: dict = {
        "main": {
            "model": plan.main_key,
            "ctx": plan.ctx,
            "batch": plan.batch,
            "ubatch": plan.ubatch,
            "parameters": plan.parameters,
        },
        "embedding": {
            "model": str(plan.embedding.candidate.path),
            "parameters": {"parallel": AUX_PARALLEL, "cache_ram": 0},
        },
        "reranker": {
            "model": str(plan.reranker.candidate.path),
            # /reranking 的每筆 query+passage 必須放進同一個 physical batch；
            # 三個值同步，使用者選 ctx 才會真的同時改變長度上限與 buffer。
            "ctx": plan.reranker_ctx,
            "batch": plan.reranker_ctx,
            "ubatch": plan.reranker_ctx,
            "parameters": {"parallel": AUX_PARALLEL, "cache_ram": 0},
        },
        "vl": {
            "model": str(plan.vl.candidate.path),
            "mmproj": str(plan.vl.mmproj),
            # VL 固定最後啟動。讓 llama.cpp 依 embedding/reranker 的實際占用
            # 自動決定 GPU layers；server 也會把 mmproj worst-case memory 加進
            # fit target，避免 health OK 後第一張圖片才 CUDA OOM。
            "parameters": build_vl_parameters(plan),
        },
    }
    if plan.allow_remote:
        for role in services:
            services[role]["bind"] = "all-interfaces"
    return {"schema_version": 1, "profile": "defaults", "services": services}


