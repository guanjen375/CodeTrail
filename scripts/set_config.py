def _opencode_timeout_ms() -> int:
    config_text = (REPO_ROOT / "config.py").read_text(encoding="utf-8")
    match = re.search(r"^OPENCODE_MCP_TIMEOUT_MIN_MS\s*=\s*([0-9_]+)", config_text, re.MULTILINE)
    return int(match.group(1).replace("_", "")) if match else OPENCODE_TIMEOUT_FALLBACK_MS


