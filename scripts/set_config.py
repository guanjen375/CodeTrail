class SetupError(RuntimeError):
    """偵測或驗證失敗;訊息會原樣通知使用者(含修復指令)。"""


@dataclass(frozen=True)
class Gpu:
    index: int
    name: str
    total_mib: int
    free_mib: int
    uuid: str

    @property
    def selector(self) -> str:
        """啟動時綁 GPU 用的識別:UUID 比 index 穩(PCI 順序可能變)。"""
        return self.uuid if self.uuid and self.uuid != "N/A" else str(self.index)

    def describe(self) -> str:
        return f"GPU {self.index}: {self.name} | VRAM {self.total_mib} MiB(free {self.free_mib} MiB)"


@dataclass(frozen=True)
class ModelCandidate:
    path: Path            # 多 shard 模型固定指向第 1 片
    total_bytes: int      # 含所有 shard
    shards: int
    mmproj: Path | None = None            # 目錄內唯一 mmproj 時的自動配對
    mmproj_choices: tuple[Path, ...] = () # 目錄內有多個 mmproj 時的候選(需使用者選)
    vl_paired: bool = False               # 有 mmproj 配對的 VL 模型(不自動當 main)

    def describe(self) -> str:
        size = f"{self.total_bytes / GIB:.1f} GB"
        extra = f",{self.shards} shards" if self.shards > 1 else ""
        mm = f" + mmproj: {self.mmproj.name}" if self.mmproj else ""
        if not self.mmproj and self.mmproj_choices:
            mm = f"(同目錄有 {len(self.mmproj_choices)} 個 mmproj,需選擇)"
        vl = "(VL 模型)" if self.vl_paired and not mm else ""
        return f"{self.path.name}({size}{extra}){mm}{vl}"


@dataclass(frozen=True)
class ModelLayout:
    """從 GGUF tensor table 取得的 placement 資訊(不讀 tensor 內容)。"""

    tensor_bytes: int
    expert_bytes: int

    @property
    def is_moe(self) -> bool:
        return self.expert_bytes > 0


